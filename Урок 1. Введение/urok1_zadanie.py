# Задание 1 (урок 1. Введение).
# Исправить сломанный код, используя sep и end.
#
# Исходный код с ошибками:
#   print("Привет",)
#   print("Я учусь программировать на Python!!!")
#   print('', 'P', 'Y', 'T', 'H', 'O', 'N',, end='*** \n')   <- две запятые и не тот sep
#   print("***Version Python 3.10", )
#
# Нужный вывод:
#   Привет!!!
#   Я учусь программировать на Python!!!
#   ***P***Y***T***H***O***N***
#   ***Version Python 3.10***
#
# Что делает end: это то, что печатается в конце строки вместо обычного
# перехода на новую строку. Что делает sep: это разделитель между аргументами.

# Первая строка. Само слово "Привет" печатаем, а восклицательные знаки
# и переход на новую строку добавляем через end.
print("Привет", end="!!! \n")

# Вторая строка — то же самое: текст, а "!!!" и перевод строки через end.
print("Я учусь программировать на Python", end="!!! \n")

# Третья строка. Буквы передаем отдельными аргументами.
# sep='***' вставляет три звездочки между аргументами.
# Первый аргумент — пустая строка '', поэтому перед первой P тоже будет ***.
# end='*** \n' ставит звездочки и перевод строки в самом конце.
print('', 'P', 'Y', 'T', 'H', 'O', 'N', sep='***', end='*** \n')

# Четвертая строка: три звездочки в конце через end, без перехода строки.
print('***Version Python 3.10', end='***')
