# Задание 2.
# Написать программу, которая считает количество строк в прикрепленном файле zadanie2.txt.
# Файл должен находиться в том же каталоге, что и программа.
# P.S. в подсчет не включать строки, которые обозначают пропуски между частями стихотворения.

# Открываем файл на чтение. Он лежит рядом с программой, поэтому пишем только имя.
fl = open('zadanie2.txt', 'r', encoding='utf-8')

count = 0  # переменная счетчика, сюда будем складывать количество строк

for i in fl:  # перебираем файл построчно (файл сам отдает строки одну за другой)
    if i == '\n':  # пустая строка между абзацами выглядит как один переход на новую строку
        continue   # такие строки в подсчет не берем, перескакиваем итерацию
    else:
        count += 1  # все остальные строки считаем

fl.close()  # закрываем файл

print(count)  # выводим результат
