# Задание 3.
# Представленный файл zadanie3.txt разбить на 4 файла, каждый из которых содержит по одному абзацу стиха.

# Открываем исходный файл на чтение
fl = open('zadanie3.txt', 'r', encoding='utf-8')

poem = ''  # временная переменная, в ней накапливаем строки текущего абзаца
j = 0      # счетчик для имен файлов (file0.txt, file1.txt и так далее)

for i in fl:  # идем по файлу построчно
    if i != '\n':  # если строка не пустая (не только переход на новую строку)
        poem += i  # прибавляем её к текущему абзацу
    else:  # а вот пустая строка означает, что абзац закончился
        # открываем очередной файл и записываем туда накопленный абзац
        temp_fl = open(f'file{j}.txt', 'wt', encoding='utf-8')
        temp_fl.write(poem)
        temp_fl.close()
        poem = ''  # обнуляем переменную для следующего абзаца
        j += 1     # переходим к следующему имени файла
else:  # блок else у for сработает после цикла — записываем последний абзац
    temp_fl = open(f'file{j}.txt', 'wt', encoding='utf-8')
    temp_fl.write(poem)
    temp_fl.close()

fl.close()  # закрываем исходный файл
