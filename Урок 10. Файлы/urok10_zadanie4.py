# -*- coding: utf-8 -*-
# Задание 4.
# Написать функцию, которая принимает на вход два параметра: имя файла и режим открытия
# (имя файла вводится пользователем, режим указывается при вызове функции в виде литерала).
# Функция должна считать количество слов в переданном в нее файле и возвращать это количество.
# Для тестирования можно использовать текстовый файл из 2 задания.

def my_f(nam, mod):
    # открываем файл через with — он сам закроет файл после блока, даже если будет ошибка
    with open(nam, mod, encoding='utf-8') as fl:
        txt = fl.read()  # считываем весь текст из файла
        txt = txt.replace('\n', ' ')  # переходы на новую строку меняем на пробелы
        txt = txt.replace('  ', ' ')  # двойные пробелы превращаем в одиночные

        sp = []  # создаем список
        sp = txt.split()  # разбиваем текст на слова по пробелам

        # убираем из списка одиночные символы, которые не являются буквами (тире, дефисы и т.п.)
        for i in range(len(sp) - 1, -1, -1):  # идем с конца, чтобы удаление не сбивало индексы
            if len(sp[i]) == 1:  # элемент длиной в один символ
                if not sp[i].isalpha():  # и это не буква
                    del sp[i]  # значит это не слово — удаляем

        return print(f'Количество слов в файле: {len(sp)}')  # выводим длину списка


# имя файла спрашиваем у пользователя, режим передаем литералом 'r'
my_f(input('Введите имя файла: '), 'r')
