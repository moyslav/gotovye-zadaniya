# Задание 5.
# Напишите функцию, которая на вход принимает имя файла.
# Функция должна возвращать следующую информацию о файле:
#   Количество строк (предложений)
#   Количество слов
#   Количество целых чисел
#   Количество знаков препинания (точки, запятые, вопросительные знаки и др.)
# Использовать один из прикрепленных текстовых файлов для теста.

def my_f(name):
    with open(name, 'r', encoding='utf-8') as f:  # открываем файл
        txt = f.read()  # весь текст файла в переменную

        # дальше работаем с копией текста: чистим её от переходов строк и лишних пробелов
        txt1 = txt.replace('\n', ' ')
        txt1 = txt1.replace('  ', ' ')
        sp = txt1.split()  # список "слов" — всего, что разделено пробелами

        # убираем одиночные не-буквенные символы (тире и прочее), чтобы не считать их словами
        for i in range(len(sp) - 1, -1, -1):
            if len(sp[i]) == 1:
                if not sp[i].isalpha():
                    del sp[i]

        # предложения считаем по точкам: точка с пробелом или точка в конце строки
        str_count = txt.count(". ") + txt.count(".\n")
        print(f'Количество предложений: {str_count}')
        print(f'Количество слов в файле: {len(sp)}')

        # собираем "чистый" текст: оставляем только буквы, цифры и пробелы
        new_txt = ''
        for j in txt:
            if j.isdigit() or j.isalpha() or j == ' ':
                new_txt += j  # всё остальное (знаки препинания) отбрасываем

        temp_sp = new_txt.split()  # список из слов и чисел

        let = []  # сюда собираем целые числа из текста
        for i in range(len(temp_sp)):
            if temp_sp[i].isdigit():  # isdigit() вернет True только если элемент — число
                let.append(temp_sp[i])

        print(f'Количество целых чисел: {len(let)}')

        # количество знаков препинания — это разница между исходным и "очищенным" текстом
        print(f'Количество знаков: {len(txt) - len(new_txt)}')


# тестируем на прикрепленном файле (можно заменить на 'zadanie5.txt' с русским текстом)
my_f('zadanie5-us.txt')
