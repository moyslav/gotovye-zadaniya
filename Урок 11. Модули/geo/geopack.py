# Модуль geopack.py — планиметрия (фигуры на плоскости)
# В модуле собраны 6 функций, каждая решает свою геометрическую задачу.
# В каждой функции есть задокументированная строка (docstring), как того требует задание.

pi = 3.14  # округленное число Пи, чтобы не тянуть математический модуль в простые формулы


# Расчет площади круга
def s_circle(r):
    '''Функция возвращает площадь круга.
    s_circle(r - радиус круга). Формула: pi*r*r'''
    return pi * r * r


# Расчет длины окружности
def c_length(r):
    '''Функция возвращает длину окружности.
    c_length(r - радиус окружности). Формула: 2*pi*r'''
    return 2 * pi * r


# Расчет площади треугольника через основание и высоту
def s_triangle(s, h):
    '''Функция возвращает площадь треугольника.
    s_triangle(s - сторона треугольника, h - высота, проведенная к этой стороне). Формула: 0.5*s*h'''
    return 0.5 * s * h


# Расчет площади прямоугольника
def s_rectangle(a, b):
    '''Функция возвращает площадь прямоугольника.
    s_rectangle(a - первая сторона, b - вторая сторона). Формула: a*b'''
    return a * b


# Расчет площади трапеции
def s_trapezoid(a, b, h):
    '''Функция возвращает площадь трапеции.
    s_trapezoid(a - первое основание, b - второе основание, h - высота). Формула: (a+b)/2*h'''
    return (a + b) / 2 * h


# Расчет гипотенузы прямоугольного треугольника
def hypotenuse(a, b):
    '''Функция возвращает гипотенузу прямоугольного треугольника.
    hypotenuse(a - первый катет, b - второй катет). Формула: квадратный корень из a*a + b*b'''
    return (a * a + b * b) ** 0.5
