# Модуль geopack_2.py — стереометрия (объемные фигуры)
# Второй модуль пакета, тоже 6 функций с задокументированными строками.

pi = 3.14  # число Пи


# Объем куба
def v_cube(a):
    '''Функция возвращает объем куба.
    v_cube(a - ребро куба). Формула: a в кубе'''
    return a ** 3


# Объем прямоугольного параллелепипеда
def v_cuboid(a, b, c):
    '''Функция возвращает объем прямоугольного параллелепипеда.
    v_cuboid(a, b, c - стороны параллелепипеда). Формула: a*b*c'''
    return a * b * c


# Объем шара
def v_sphere(r):
    '''Функция возвращает объем шара.
    v_sphere(r - радиус шара). Формула: 4/3*pi*r в кубе'''
    return 4 / 3 * pi * r ** 3


# Объем цилиндра
def v_cylinder(r, h):
    '''Функция возвращает объем цилиндра.
    v_cylinder(r - радиус основания, h - высота цилиндра). Формула: pi*r*r*h'''
    return pi * r * r * h


# Объем конуса
def v_cone(r, h):
    '''Функция возвращает объем конуса.
    v_cone(r - радиус основания, h - высота конуса). Формула: 1/3*pi*r*r*h'''
    return 1 / 3 * pi * r * r * h


# Объем пирамиды с прямоугольным основанием
def v_pyramid(a, b, h):
    '''Функция возвращает объем пирамиды с прямоугольным основанием.
    v_pyramid(a, b - стороны основания, h - высота пирамиды). Формула: 1/3*a*b*h'''
    return 1 / 3 * a * b * h
