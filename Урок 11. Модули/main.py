#   geo/             - папка пакета
#       geopack.py   - модуль с планиметрией (плоские фигуры)
#       geopack_2.py - модуль со стереометрией (объемные фигуры)
# Папка __init__.py в пакете не обязательна, в Python 3 пакет работает и без него.

# Подключаем оба модуля из нашего пакета geo
from geo import geopack
from geo import geopack_2

# Проверяем модуль с планиметрией: вызываем каждую функцию и печатаем результат
print('--- Планиметрия ---')
print(f'Площадь круга с радиусом 3: {geopack.s_circle(3)}')
print(f'Длина окружности с радиусом 3: {geopack.c_length(3)}')
print(f'Площадь треугольника (сторона 4, высота 5): {geopack.s_triangle(4, 5)}')
print(f'Площадь прямоугольника (2 и 6): {geopack.s_rectangle(2, 6)}')
print(f'Площадь трапеции (основания 3 и 5, высота 4): {geopack.s_trapezoid(3, 5, 4)}')
print(f'Гипотенуза (катеты 3 и 4): {geopack.hypotenuse(3, 4)}')

# Проверяем модуль со стереометрией
print('--- Стереометрия ---')
print(f'Объем куба с ребром 3: {geopack_2.v_cube(3)}')
print(f'Объем параллелепипеда (1, 2, 3): {geopack_2.v_cuboid(1, 2, 3)}')
print(f'Объем шара с радиусом 2: {geopack_2.v_sphere(2)}')
print(f'Объем цилиндра (радиус 2, высота 5): {geopack_2.v_cylinder(2, 5)}')
print(f'Объем конуса (радиус 2, высота 6): {geopack_2.v_cone(2, 6)}')
print(f'Объем пирамиды (2, 4, высота 6): {geopack_2.v_pyramid(2, 4, 6)}')

