"""
Задание 2 (урок 14. Исключения).
Внизу приведен код. При его работе может возникать ошибка деления на ноль.
Необходимо написать обработчик исключения, так чтобы при делении на ноль
выводилось сообщение: "Нам попался НОЛЬ"
"""

import random  # модуль для генерации случайных чисел


def my_f():
    for i in range(10):
        # random.randint(0, 10) может выдать 0, и тогда i / 0 вызовет ZeroDivisionError
        try:
            d = i / random.randint(0, 10)
        except ZeroDivisionError:  # ловим именно деление на ноль
            print('Нам попался НОЛЬ')
        else:  # блок else сработает, если ошибки не было
            print(d)


my_f()
