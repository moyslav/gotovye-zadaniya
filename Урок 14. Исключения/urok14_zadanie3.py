# -*- coding: utf-8 -*-
"""
Задание 3 (урок 14. Исключения).
Написать программу, которая запрашивает у пользователя 10 слов и помещает их в список.
НО если пользователь ввел слово end, программа должна вызвать принудительно
исключение TypeError с сообщением "Тут мы и завершим работу".
"""

sp = []  # пустой список для слов

for i in range(10):  # всего 10 слов
    try:
        n = input('Введите слово: ')
        if n.lower() == 'end':  # сравниваем в нижнем регистре, чтобы ловить END, End и т.п.
            raise TypeError  # принудительно вызываем исключение
    except TypeError:
        print('Тут мы и завершим работу')  # сообщение из задания
        break  # выходим из цикла, дальше слова не собираем
    else:  # исключения не было — слово нормальное, добавляем в список
        sp.append(n)

print(sp)  # печатаем что накопилось
