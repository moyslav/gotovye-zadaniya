# -*- coding: utf-8 -*-
"""
Задание 5 (урок 14. Исключения).
За основу возьмем задание из урока Словари.
Создать словарь, в котором в качестве ключа содержится номер студенческого билета
(номер билета трехзначный т.е. от 0 до 999), а в качестве значения содержится строка
с именем и фамилией. Заполняется словарь вводом с клавиатуры, номер билета генерируется
случайно, но проверяется чтобы он не использовался в словаре.
Изменить код так, чтобы цикл был не на 10 повторений, а бесконечный.
Создать собственное исключение EndError.
Если при вводе имени и фамилии пользователь указывает EXIT (в любом регистре),
то будет вызываться созданное нами исключение.
Внутри исключения у нас будет вывод сообщения:
"Ну вот мы и остановились. Тут и завершим"
И после должен быть вывод словаря, что у нас получился.
"""

import random  # для генерации номера билета


class EndError(Exception):
    # наше собственное исключение, наследуемся от стандартного Exception
    # сообщение печатаем прямо в конструкторе, как в решении урока
    def __init__(self):
        print("Ну вот мы и остановились. Тут и завершим")


slovar = {}  # создаем пустой словарь

while True:  # цикл теперь бесконечный
    n = random.randint(0, 999)  # генерируем номер билета от 0 до 999
    if n in slovar.keys():  # проверяем есть ли такой номер уже в словаре
        continue  # если есть — просто генерируем новый на следующей итерации
    else:
        try:
            m = input("Введите Фамилию и Имя: ")  # запрашиваем ФИО
            if m.lower() == 'exit':  # EXIT в любом регистре
                raise EndError  # вызываем наше собственное исключение
        except EndError:
            break  # по исключению останавливаем заполнение словаря
        else:  # исключения не было — добавляем пару в словарь
            slovar[n] = m

print(slovar)  # выводим словарь, который у нас получился
