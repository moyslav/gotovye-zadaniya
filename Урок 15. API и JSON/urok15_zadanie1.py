# -*- coding: utf-8 -*-
"""
Задание 1 (урок 15. API, JSON).
За основу взято задание из урока Словари: словарь, где ключ — номер
студенческого билета (от 0 до 999), а значение — имя и фамилия.
Номер генерируется случайно и проверяется, что он еще не занят.

Что нужно переделать:
1. Цикл не на 10 повторений, а бесконечный.
2. Программа останавливается, когда пользователь вводит "END" (в любом регистре).
3. Готовый словарь записывается в файл формата .json с отступами (indent),
   чтобы запись была структурированной.
"""

import random  # нужен для случайного номера билета
import json    # модуль для работы с json-файлами

slovar = {}  # здесь будет храниться весь словарь

while True:  # цикл теперь бесконечный, выходим из него только через break
    n = random.randint(0, 999)  # генерируем трехзначный номер билета
    if n in slovar.keys():  # если такой номер уже есть в словаре
        continue  # просто переходим на новую итерацию — сгенерируем другой
    else:
        m = input("Введите Фамилию и Имя: ")  # запрашиваем ФИО у пользователя
        if m.lower() == 'end':  # приводим к нижнему регистру, чтобы ловить END, End и т.д.
            break  # пользователь закончил ввод — выходим из цикла
        slovar[n] = m  # добавляем пару "номер билета: ФИО" в словарь

# Записываем словарь в json-файл.
# encoding='utf-8' — чтобы не было проблем с русскими буквами,
# ensure_ascii=False — чтобы русские буквы писались как есть, а не \u0410...,
# indent=4 — чтобы файл был читаемым, с отступами.
with open('db.json', 'w', encoding='utf-8') as fl:
    json.dump(slovar, fl, indent=4, ensure_ascii=False)

print(slovar)  # для наглядности показываем словарь и в консоли
