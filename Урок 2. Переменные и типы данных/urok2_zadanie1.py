# Задание 1 (урок 2).
# Программа запрашивает число и показывает соседей: на 1 меньше и на 1 больше.
#
# Формат вывода по заданию:
# Введенное число: X, число меньше на 1: X-1, число большее на 1: X+1

# int() превращает введенную строку в целое число, иначе с ней не посчитать.
x = int(input('Введите число: '))

# Выводим все в одну строку через запятую в print.
# print сам склеивает аргументы через пробел — так код короче и понятнее.
print('Введенное число: ', x, ' Число меньше на 1: ', x - 1, ' Число больше на 1: ', x + 1)
