# -*- coding: utf-8 -*-
# Задание 2 (урок 2).
# Программа знакомится с пользователем и показывает типы переменных.
#
# По заданию:
# - имя сохранить в my_name
# - год рождения в year_of_birth
# - посчитать возраст в age
# - вывести типы всех трех переменных
# - вывести "Hello my name is: my_name, My age: age"

my_name = input('Введите имя: ')              # имя — это строка (str)
year_of_birth = input('Введите год рождения: ')  # тут пока строка, потому что input всегда отдает str

# Считаем возраст. Год берем как в листинге курса — от 2022.
# int(year_of_birth) превращает строку в число, иначе вычитание не сработает.
age = 2022 - int(year_of_birth)

# Выводим типы всех трех переменных через запятую в print.
# type() показывает, к какому классу относится значение.
print(type(my_name), type(year_of_birth), type(age))

# Финальное сообщение по образцу.
print('Hello, my name is:', my_name, 'My age: ', age)
