# Задание 3 (урок 2).
# Переводим минуты в формат ЧЧ:ММ.
#
# Целых часов будет столько, сколько раз 60 влезает в число минут (//),
# а остаток от деления на 60 (%) — это оставшиеся минуты.
# Пример: 136 минут = 2 часа и 16 минут.

t = int(input('Введите количество минут: '))

# Печатаем "Прошло: ", потом часы, двоеточие, минуты и хвост фразы.
# sep='' нужен, чтобы между аргументами не было пробелов —
# иначе получилось бы "2 : 16" вместо "2:16".
print('Прошло: ', t // 60, ':', t % 60, ' с начала дня', sep='')
