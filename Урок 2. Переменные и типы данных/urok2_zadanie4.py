# Задание 4 (урок 2).
# Считаем, сколько столов нужно закупить в кабинет.
#
# Условия: два сотрудника за столом, отдельно стол руководителю
# и еще один стол для кофе-брейка.
#
# Для сотрудников округляем деление вверх через math.ceil:
# если сотрудников 5, то 5/2 = 2.5 -> 3 стола.

import math  # подключаем модуль math для функции ceil

x = int(input('Введите количество работников: '))  # сколько человек в кабинете
st = math.ceil(x / 2)  # столов для сотрудников, округляем вверх
# Плюс 2 стола: один руководителю и один для кофе-брейка.
print('Необходимо купить: ', st + 2, 'столов(-а)')
