# Задание 5 (урок 2).
# Смотрим типы данных у переменных и у результатов операций.
#
# Даны:
#   a = 22      -> int
#   b = '43.0'  -> str (это строка, хоть и похожа на число)
#   c = 30.99   -> float
#   n = 2 + 2j  -> complex
#
# Строку '43.0' нельзя сложить с комплексным числом, поэтому по подсказке
# задания сначала преобразуем ее функцией complex.

a = 22
b = '43.0'
c = 30.99
n = 2 + 2j

# Выводим тип каждого исходного значения. type() покажет класс переменной.
print('Переменная a со значением:', a, 'имеет тип', type(a))
print('Переменная b со значением:', b, 'имеет тип', type(b))
print('Переменная c со значением:', c, 'имеет тип', type(c))
print('Переменная n со значением:', n, 'имеет тип', type(n))

# Теперь проверяем типы результатов операций.
m = c + a          # float + int = float
h = complex(b) + n  # превращаем строку в комплексное и складываем с n
k = a / 2          # деление всегда дает float

print('Переменная m со значением:', m, 'имеет тип', type(m))
print('Переменная h со значением:', h, 'имеет тип', type(h))
print('Переменная k со значением:', k, 'имеет тип', type(k))
