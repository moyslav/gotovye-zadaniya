# Задание 1 (урок 3).
# Определяем наибольшее и наименьшее из трех чисел.
#
# Ищем так же, как в жизни: просто сравниваем числа между собой.

x = int(input('Введите первое число: '))
y = int(input('Введите второе число: '))
z = int(input('Введите третье число: '))

# Ищем большее число. Проверяем каждое: больше ли оно двух остальных.
if x > y and x > z:
    print('Большее число: ', x)
elif y > x and y > z:
    print('Большее число: ', y)
elif z > x and z > y:
    print('Большее число: ', z)

# По такой же схеме ищем меньшее — только сравниваем на "меньше".
if x < y and x < z:
    print('Меньшее число: ', x)
elif y < x and y < z:
    print('Меньшее число: ', y)
elif z < x and z < y:
    print('Меньшее число: ', z)
