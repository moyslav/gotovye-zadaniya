# Задание 2 (урок 3).
# Определяем время года по номеру месяца рождения.
#
# Зима: 12, 1, 2. Весна: 3-5. Лето: 6-8. Осень: 9-11.

x = int(input('Введите месяц рождения: '))

# Проверяем по диапазонам. Для зимы месяц 12 идет отдельно,
# потому что он не входит в непрерывный отрезок 1-2.
if x == 12 or 1 <= x <= 2:
    print('Вы родились зимой!')
elif 3 <= x <= 5:
    print('Вы родились весной!')
elif 6 <= x <= 8:
    print('Вы родились летом!')
elif 9 <= x <= 11:
    print('Вы родились осенью!')
else:
    # Сюда попадаем, если ввели число вне 1-12.
    print('Вы ввели неизвестный месяц')
