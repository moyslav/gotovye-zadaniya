# Задание 3 (урок 3).
# Выводим все числа от 0 до N через while.

x = int(input('Введите число: '))
i = 0  # счетчик цикла, начинаем с нуля

# Работаем, пока счетчик не дошел до введенного числа включительно.
while i <= x:
    print(i)   # выводим текущее число
    i += 1     # увеличиваем счетчик, иначе цикл вечный
