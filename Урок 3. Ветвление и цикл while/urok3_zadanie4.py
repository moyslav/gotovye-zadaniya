# Задание 4 (урок 3).
# Считаем количество четных цифр в числе и их сумму через while.
#
# Разбираем число по цифрам: последняя цифра — это остаток от деления на 10,
# а после обработки отбрасываем ее целочисленным делением на 10.

x = int(input('Введите число: '))
count = 0  # количество четных цифр
summ = 0   # сумма четных цифр

while x > 0:
    a = x % 10         # берем последнюю цифру числа
    if a % 2 == 0:     # проверяем цифру на четность
        count += 1     # четная — увеличиваем счетчик
        summ += a      # и прибавляем к сумме
    x = x // 10        # отбрасываем последнюю цифру

print('Количество четных цифр: ', count)
print('Сумма четных цифр: ', summ)
