# Задание 5 (урок 3).
# Выводим все числа от X до R и считаем их количество.
# По условию X < R, и оба края включаются в подсчет.

x = int(input('Введите число 1: '))  # первое число
r = int(input('Введите число 2: '))  # второе число
count = 0  # сюда считаем количество чисел

# Идем от X до R включительно, поэтому условие x <= r.
while x <= r:
    print(x)      # выводим текущее число
    count += 1    # считаем его
    x += 1        # переходим к следующему числу

print('В промежутке : ', count, 'чис(-ла)/(-ел)')
