# Задание 6 (урок 3).
# Считаем факториал числа через while.
# Факториал — произведение чисел от 1 до F.

x = int(input('Введите число: '))  # запрашиваем число

f = 1  # тут храним факториал, начинаем с 1
i = 1  # счетчик, перебирающий числа от 1 до x
while i <= x:
    f *= i   # домножаем факториал на текущее число
    i += 1   # увеличиваем счетчик

print('Факториал числа:', x, 'равен: ', f)
