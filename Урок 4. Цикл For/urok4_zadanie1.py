# Вывести все нечетные числа от 2 до 150 через цикл for.
# Без if — просто проходим по нужному диапазону.

# Вариант 1: начинаем с 3 и идем через шаг 2.
# range(начало, конец, шаг) — конец 150 не включается, но 149 войдет.
