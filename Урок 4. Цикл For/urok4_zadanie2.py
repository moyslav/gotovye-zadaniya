# Задание 2 (урок 4).
# Сумма всех четных чисел от 0 до N включительно.
# Цикл for: проходим только по четным, чтобы не проверять каждое число.

n = int(input('Введите число: '))
summ = 0  # переменная, в которой будем собирать сумму

# Начинаем с 0, шаг 2. Н+1, потому что конечная точка в range не включается,
# а число N само может быть четным и его нужно захватить.
for i in range(0, n + 1, 2):
    summ += i

print(summ)
