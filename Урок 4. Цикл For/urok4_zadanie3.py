# Задание 3 (урок 4).
# Выводим числа от 1 до T, пропуская 7, 13, 21 и 29.
# T должно быть >= 35. Используем continue для пропуска.

t = int(input('Введите число: '))

# Сначала проверяем, что число подходит под условие.
if t >= 35:
    for i in range(1, t):  # идем до t-1, потому что условие "от 1 до T"
        # Если встречаем одно из этих чисел — пропускаем итерацию.
        if i == 7 or i == 13 or i == 21 or i == 29:
            continue  # переходим сразу к следующему i
        else:
            print(i)  # выводим число, если не попало под исключение
else:
    print("Введенное число не подходит")  # T меньше 35
