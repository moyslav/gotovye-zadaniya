# Задание 4 (урок 4).
# Игра "Угадай число": компьютер загадывает от 0 до 4,
# а пользователь пытается угадать.

import random  # модуль для генерации случайных чисел

x = random.randint(0, 4)  # компьютер загадывает

while True:  # бесконечный цикл — выйдем из него только когда пользователь угадает
    m = int(input('Введите число: '))
    if m == x:
        print("Вы угадали")
        break  # выходим из цикла
    else:
        print('Неудача, повторите ввод')
