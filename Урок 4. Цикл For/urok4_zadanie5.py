# Задание 5 (урок 4).
# Вложенными циклами for выводим единичную матрицу 5 на 5.
# На главной диагонали — единицы, остальное — нули.

# Сначала выведем матрицу, полностью заполненную нулями,
# чтобы понять, как работают вложенные циклы.
for i in range(5):            # внешний цикл — строки
    for j in range(5):        # внутренний цикл — столбцы
        print('0', end=' ')   # печатаем 0, а не переходим на новую строку
    print()                   # пустой print переводит курсор на новую строку

# Теперь добавим условие: когда номер строки равен номеру столбца (i == j),
# печатаем 1 — это и есть главная диагональ.
for i in range(5):
    for j in range(5):
        if i == j:            # диагональ — индексы совпадают
            print('1', end=' ')
        else:
            print('0', end=' ')
    print()
