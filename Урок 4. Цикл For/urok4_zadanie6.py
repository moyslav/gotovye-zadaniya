# Задание 6 (урок 4).
# Числа от 1 до N: четные возводим в квадрат, нечетные — в куб.

n = int(input('Введите число: '))

# range до n + 1, потому что n само должно участвовать в выводе.
for i in range(1, n + 1):
    if i % 2 != 0:  # остаток от деления на 2 не равен нулю — значит число нечетное
        print(i, ' в степени 3 = ', i ** 3)
    else:
        print(i, ' в степени 2 = ', i ** 2)
