# -*- coding: utf-8 -*-
# Урок 5. Задание №1. Поменять два слова местами.
#
# Пользователь вводит два слова через пробел, например "привет мир",
# а программа должна вывести "мир привет".
#
# У строк в Python есть удобный метод split() — он режет строку
# по пробелам и возвращает список частей. split() без аргументов
# режет по любым пробелам и не создаёт пустых кусков.

# Получаем строку от пользователя.
s = input("Введите два слова через пробел: ")

# Режем на части: получим список из двух слов, например ['привет', 'мир'].
words = s.split()

# Меняем элементы местами через распаковку кортежа —
# классический питоновский способ без временной переменной.
words[0], words[1] = words[1], words[0]

# Склеиваем слова обратно в строку через пробел методом join
# и выводим результат.
print(' '.join(words))
