# -*- coding: utf-8 -*-
# Урок 5. Задание №2. Считаем буквы 'a' и 'o' в строке.
#
# Порядок действий:
# 1. приводим строку к нижнему регистру методом lower(),
#    чтобы 'A' и 'a' считались одной и той же буквой
# 2. считаем вхождения через count()
# 3. если букв нет вообще — выводим особое сообщение

# Строка вводится на английском (так сказано в задании).
s = input("Введите строку на английском: ")

# lower() переводит ВСЕ буквы в маленькие. 'Apple' -> 'apple'.
# Так нам не придётся отдельно считать заглавные буквы.
s = s.lower()

# Метод count('x') возвращает, сколько раз подстрока встречается в строке.
count_a = s.count('a')
count_o = s.count('o')

# Проверяем случай, когда ни той, ни другой буквы нет.
if count_a == 0 and count_o == 0:
    print("В введенном предложении нет букв 'o' и 'a'")
else:
    # По заданию выводим оба счётчика в заданном формате.
    print(f"Буква 'a' встречается {count_a} раз")
    print(f"Буква 'o' встречается {count_o} раз")
