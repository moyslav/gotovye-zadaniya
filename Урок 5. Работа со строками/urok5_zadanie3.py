# Урок 5. Задание №3. Считаем цифры в строке.
#
# У строк есть метод isdigit() — он возвращает True, если символ цифра.
# Перебираем строку посимвольно и считаем только цифры.

# Вводим строку, в которой могут быть и буквы, и цифры.
s = input("Введите строку: ")

count = 0  # счётчик цифр

# Цикл for по строке отдаёт по одному символу за итерацию.
for char in s:
    if char.isdigit():
        # Символ оказался цифрой — увеличиваем счётчик.
        count += 1

# Показываем результат.
print(f"В введенной строке : {count} цифр")
