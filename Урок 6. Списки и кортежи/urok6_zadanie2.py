# Задание 2 (урок 6).
# Список из N случайных целых чисел от 0 до 20.

import random  # модуль случайных чисел

sp = []  # создаем пустой список
n = int(input('Введите длину списка: '))  # спрашиваем у пользователя длину

for i in range(n):                 # повторяем N раз
    p = random.randint(0, 20)      # генерируем случайное число
    sp.append(p)                   # добавляем в конец списка

print(sp)  # выводим готовый список
