# Список из 10 введенных чисел, потом удаляем элементы с четными индексами.

sp = []  # пустой список

for i in range(10):  # 10 повторений — заполняем список с клавиатуры
    v = int(input('Введите число: '))
    sp.append(v)

print(sp)  # показываем исходный список

# Вариант 1: срез с шагом 2 начиная с индекса 1 —
# остаются только элементы с нечетными индексами.
sp = sp[1::2]
print(sp)

