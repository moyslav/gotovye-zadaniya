# Задание 4 (урок 6).
# Список из 10 случайных чисел от 0 до 100: сортируем
# и считаем сумму второго и предпоследнего элементов.

import random  # модуль случайных чисел

sp = []  # пустой список

for i in range(10):                # 10 повторений
    sp.append(random.randint(0, 100))  # заполняем случайными числами

print(sp)   # исходный список
sp.sort()   # сортируем по возрастанию
print(sp)   # отсортированный список

s = 0
s = sp[1] + sp[-2]  # второй элемент (индекс 1) и предпоследний (индекс -2)
print(s)
