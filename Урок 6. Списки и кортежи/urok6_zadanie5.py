# Задание 5 (урок 6).
# Список из 10 случайных чисел. Удаляем все, что меньше 5,
# и считаем среднее арифметическое оставшихся.

import random  # модуль случайных чисел

sp = []  # пустой список
n = int(input('Введите конец диапазона: '))  # конец диапазона, больше 5

for i in range(10):              # 10 повторений
    v = random.randint(0, n)     # генерируем число
    sp.append(v)                 # добавляем в список

print(sp)  # исходный список

# Вариант 1: генератор списка — берем только элементы больше 5.
sp = [i for i in sp if i > 5]
print(sp)

# Вариант 2: удалять через del с конца, чтобы индексы не съезжали.
# for j in range(len(sp) - 1, 0, -1):
