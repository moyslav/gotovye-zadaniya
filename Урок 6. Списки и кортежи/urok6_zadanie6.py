# Список из 20 случайных чисел от 0 до 20.
# Ищем произведение элементов, кратных 3 и стоящих на четных индексах.

import random  # модуль случайных чисел

sp = []    # пустой список
proizv = 1  # произведение, начинаем с 1

for i in range(20):                    # 20 повторений
    sp.append(random.randint(0, 20))   # заполняем список

print(sp)  # показываем список

# Перебираем индексы, а не значения — нам важна позиция элемента.
for j in range(len(sp)):
    if j % 2 == 0:        # индекс четный
        if sp[j] % 3 == 0:  # значение кратно 3
            proizv *= sp[j]  # домножаем произведение
            # Для отладки можно выводить, какой элемент участвует:
            # print(sp[j], ' ', j)

print(proizv)
