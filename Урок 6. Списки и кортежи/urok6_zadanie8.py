# Задание 8 (урок 6).
# Проверяем, счастливый ли билет. Счастливый — если сумма первых
# трех цифр равна сумме последних трех. Номер от 000000 до 999999.

n = input('Введите номер билета: ')  # вводим как строку, чтобы работать с цифрами
sp = list(n)  # превращаем строку в список символов

# Список пока из строк, а нам нужны числа — преобразуем каждый элемент в int.
for i in range(len(sp)):
    sp[i] = int(sp[i])

print(sp)

first = sum(sp[:3])   # сумма первых трех цифр (срез от начала до индекса 3)
second = sum(sp[3:])  # сумма последних трех (срез от индекса 3 до конца)

if first == second:
    print("Билет счастливый")
else:
    print("Билет обычный")
