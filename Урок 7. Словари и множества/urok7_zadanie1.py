# Русско-английский словарь. Пользователь вводит русское слово —
# выводим перевод. Ключи словаря — русские слова.

slovar = {
    "кот": "cat",
    "мышь": "mouse",
    "собака": "dog",
    "животные": "animals",
    "дверь": "door"
}

x = input("Введите слово: ")  # запрашиваем слово
if x in slovar.keys():        # проверяем, есть ли такой ключ в словаре
    print(f'Слово {x} переводится как {slovar[x]}')  # выводим значение по ключу
else:
    print("Введенного слова нет")  # ключа нет — сообщаем об этом
