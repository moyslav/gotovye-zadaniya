# Доработанный словарь: пользователь может добавить 5 своих слов.

slovar = {
    "кот": "cat",
    "мышь": "mouse",
    "собака": "dog",
    "животные": "animals",
    "дверь": "door"
}

x = input("Введите слово: ")  # сначала ищем слово, как в первом задании
if slovar.get(x):             # get возвращает значение или None, удобно для проверки
    print(f'Слово {x} переводится как {slovar[x]}')
else:
    print("Введенного слова нет")

# Теперь добавляем 5 новых слов.
i = 1
while i <= 5:  # цикл на 5 добавлений
    n = input('Введите русское слово которое нужно добавить: ')
    if n in slovar.keys():  # такое слово уже есть в словаре
        n = input('Такое слово уже есть, введите другое: ')
    else:
        m = input('Введите перевод')  # спрашиваем перевод
        slovar[n] = m  # добавляем пару ключ: значение
        i += 1         # увеличиваем счетчик только после успешного добавления

print(slovar)  # показываем итоговый словарь
