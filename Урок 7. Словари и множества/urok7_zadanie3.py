# Задание 3 (урок 7).
# Словарь студентов: ключ — номер билета (генерируется случайно и не повторяется),
# значение — фамилия и имя. Заполняем 10 записями.

import random  # для генерации номеров

slovar = {}  # пустой словарь
i = 0

while i < 10:  # нужно заполнить 10 записей
    n = random.randint(0, 12)   # генерируем номер билета
    if n in slovar.keys():      # такой номер уже занят
        n = random.randint(0, 12)  # генерируем другой
    else:
        m = input("Введите Фамилию и Имя")  # запрашиваем данные студента
        slovar[n] = m  # добавляем в словарь
        i += 1         # считаем только уникальные записи

print(slovar)
