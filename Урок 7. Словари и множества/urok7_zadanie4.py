# Фильтруем словарь по длине: ключи до 4 символов и значения от 5 символов.

slovar = {
    "кот": "cat",
    "мышь": "mouse",
    "собака": "dog",
    "животные": "animals",
    "дверь": "door"
}

for i in slovar.keys():  # перебираем ключи
    if len(i) <= 4:      # длина ключа 4 символа или меньше
        print(i)
print()                  # пустая строка для читаемости

for j in slovar.values():  # перебираем значения
    if len(j) >= 5:        # длина значения 5 символов или больше
        print(j)
