# Задание 5 (урок 7).
# Два множества по 20 уникальных случайных чисел от 0 до 100.
# Выводим объединение, разность и пересечение.

import random  # модуль случайных чисел

mn = set()   # первое множество
mn2 = set()  # второе множество
i = 0        # счетчик

# Множество хранит только уникальные элементы, поэтому перед добавлением
# проверяем, нет ли уже такого числа — иначе элементов будет меньше 20.
while i < 20:
    n = random.randint(0, 100)
    if n not in mn:
        mn.add(n)   # добавляем число
        i += 1      # считаем только новые
print(mn, len(mn))

i = 0  # обнуляем счетчик для второго множества
while i < 20:
    n = random.randint(0, 100)
    if n not in mn2:
        mn2.add(n)
        i += 1
print(mn2, len(mn2))

print("Объединение: ", mn | mn2)   # все элементы обоих множеств
print('Разность ', mn - mn2)       # то, что есть в mn, но нет в mn2
print("Пересечение ", mn & mn2)    # то, что есть в обоих множествах
