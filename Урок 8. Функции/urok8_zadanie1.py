# Задание 1 (урок 8).
# Функция считает площадь круга по радиусу.
# Формула: S = pi * R^2.

import math  # модуль math, чтобы взять точное число pi


def fun_s(r):          # функция принимает радиус
    s = math.pi * (r ** 2)  # считаем площадь по формуле
    return s           # возвращаем результат


rad = int(input('Введите радиус: '))  # радиус вводит пользователь
print(fun_s(rad))                     # вызываем функцию и печатаем ответ
