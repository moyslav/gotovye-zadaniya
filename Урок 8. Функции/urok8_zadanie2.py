# Задание 2 (урок 8).
# Функция считает количество четных цифр в числе и их сумму.


def my_f(num):  # функция принимает целое число
    k = 0       # счетчик четных цифр
    s = 0       # сумма четных цифр
    while num > 0:      # работаем, пока цифры не кончатся
        tm1 = num % 10  # последняя цифра числа
        if tm1 % 2 == 0:  # цифра четная?
            k += 1        # увеличиваем счетчик
            s += tm1      # прибавляем к сумме
        num //= 10        # отбрасываем последнюю цифру
    return print(f"Количество четных цифр {k} \nСумма четных цифр {s}")


nm = int(input('Введите число: '))  # запрашиваем число
my_f(nm)  # вызываем функцию
