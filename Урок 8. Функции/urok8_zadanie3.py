# Функция считает факториал числа. Модуль math не используем.


def my_f(num):  # функция принимает число
    i = 1       # счетчик для перебора чисел
    fc = 1      # переменная факториала
    while i <= num:  # перебираем от 1 до num
        fc *= i      # домножаем
        i += 1       # следующий шаг
    return print(f"Факториал числа {num} равен {fc}")


n = int(input("Введите число: "))  # запрашиваем число
my_f(n)  # вызываем функцию
