# Задание 4 (урок 8).
# Функция принимает список из 15 случайных чисел от 1 до 30
# и возвращает отсортированный (по убыванию) список из четных элементов.

import random  # модуль случайных чисел


def my_f(sp):         # функция принимает список
    new_sp = []       # сюда соберем только четные элементы
    for i in range(len(sp)):  # перебираем индексы
        if sp[i] % 2 == 0:    # элемент четный?
            new_sp.append(sp[i])  # добавляем в новый список
    new_sp.sort(reverse=True)  # сортируем по убыванию
    return new_sp  # возвращаем готовый список


old_sp = []  # исходный список
for i in range(15):                       # 15 повторений
    old_sp.append(random.randint(1, 30))  # заполняем случайными числами

print(old_sp)       # показываем исходный список
print(my_f(old_sp))  # результат работы функции
