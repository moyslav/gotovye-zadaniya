# Задание 6 (урок 8).
# Функция проверяет, простое ли число.
# Простое число делится только на 1 и на само себя.


def my_f(num):  # функция принимает число
    k = 0       # счетчик делителей
    for i in range(1, num + 1):  # перебираем числа от 1 до num
        if num % i == 0:  # делится без остатка — это делитель
            k += 1
    if k > 2:  # делителей больше двух — число не простое
        return print("Число не простое")
    else:
        return print('число простое')


nm = int(input('Введите число: '))
my_f(nm)  # вызываем функцию
