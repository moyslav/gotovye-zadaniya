# Урок 9. Задание №1. Считаем звёздочки при рекурсивном вызове.
#
# Исходная функция F(n) печатает звёздочки и рекурсивно вызывает
# саму себя. Задание — посчитать, СКОЛЬКО всего звёздочек напечатается
# при вызове F(140).
#
# Идея: глобальный счётчик. Каждый раз перед print увеличиваем его.
# Ещё проще — сделать счётчик параметром функции по умолчанию,
# но в уроке про global ещё не было, поэтому воспользуемся простым
# приёмом: функция возвращает количество звёздочек, а print печатает.
#
# Разбор исходного кода:
#   F(n) печатает 1 звезду всегда;
#   если n >= 1, печатает ещё одну и вызывает F(n-1) и F(n//2).
# Рекурсия раскручивается, пока n >= 1. Значит при n = 0 и n < 0
# печатается только одна звезда и рекурсия останавливается.

def F(n):
    """Печатает звёздочки и возвращает их общее количество."""
    count = 1  # эта звезда печатается при любом n
    print('*')
    if n >= 1:
        # Печатаем вторую звезду и учитываем её.
        print('*')
        count += 1
        # Складываем звёзды из обеих веток рекурсии:
        # возвращает количество звёзд, напечатанных этими вызовами.
        count += F(n - 1)
        count += F(n // 2)
    return count

# --- Основная часть ---

# Вызываем функцию с аргументом 140.
total = F(140)

# Печатаем итоговое количество звёздочек.
print(f"Всего напечатано звёздочек: {total}")
