# Урок 9. Задание №3. Цифры из строки через filter и lambda.
#
# filter(условие, последовательность) оставляет только те элементы,
# для которых условие вернуло True. Условие задаём лямбда-функцией:
# лямбда — это функция без имени, записанная в одну строку.
#
# filter возвращает не список, а специальный объект, поэтому
# его нужно обернуть в list(), чтобы получить нормальный список.
#
# Важно: map/filter не принимают лямбду с двумя выражениями,
# поэтому isdigit вызываем у символа: lambda c: c.isdigit()

# Строку вводит пользователь.
s = input("Введите строку: ")

# Оставляем только символы, для которых isdigit() вернул True.
# c — очередной символ строки (лямбда получает его как аргумент).
digits = list(filter(lambda c: c.isdigit(), s))

# Печатаем итоговый список цифровых символов.
print(digits)
