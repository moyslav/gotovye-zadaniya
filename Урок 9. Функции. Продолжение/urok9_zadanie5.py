# Урок 9. Задание №5. Декоратор: замер времени работы функции факториала.
#
# Декоратор — это функция, которая принимает функцию и возвращает
# обёрнутую версию с дополнительным поведением. Здесь дополнительное
# поведение — замер времени выполнения.
#
# Как это работает:
# 1. time.time() до вызова — текущее время в секундах
# 2. вызываем оригинальную функцию
# 3. time.time() после вызова
# 4. разность — время работы в секундах

import time  # модуль для работы со временем

def timer(func):
    """Декоратор, который замеряет время выполнения функции func."""
    def wrapper(*args, **kwargs):
        start = time.time()          # запоминаем время старта
        result = func(*args, **kwargs)  # вызываем оригинальную функцию
        end = time.time()            # время после выполнения
        # Печатаем, сколько секунд работала функция. Формат .6f —
        # шесть знаков после точки, чтобы видеть доли секунды.
        print(f"Функция {func.__name__} выполнялась {end - start:.6f} сек")
        return result  # не забываем вернуть результат самой функции
    return wrapper

# Вешаем декоратор на функцию факториала (из задания 3 прошлого урока).
@timer
def factorial(f):
    """Считает факториал числа f."""
    result = 1
    for i in range(1, f + 1):
        result *= i  # домножаем накопитель на каждый множитель
    return result

# --- Основная часть ---

# Число вводит пользователь. Возьмем большое число, чтобы
# замер времени был заметнее.
n = int(input("Введите число: "))

# Вызов выглядит обычно, но на самом деле сработает обёртка wrapper
# и напечатает время выполнения.
print(f"Факториал числа {n} равен {factorial(n)}")
