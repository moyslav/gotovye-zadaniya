# -*- coding: utf-8 -*-
# Урок 1. Задание на исправление кода через sep и end.
#
# Суть задания: ниже был сломанный код, его нужно починить так,
# чтобы вывод на экран совпал с образцом:
#
#   Привет!!!
#   Я учусь программировать на Python!!!
#   ***P***Y***T***H***O***N***
#   ***Version Python 3.10***
#
# Разбор ошибок в исходном коде:
# 1) print("Привет",)  — после "Привет" стояла запятая, поэтому печаталось
#    просто "Привет", а нам нужно "Привет!!!". Значит в скобках должен быть
#    один аргумент "Привет!!!" без всяких запятых.
# 2) print('', 'P', 'Y', 'T', 'H', 'O', 'N',, end='*** \n') — здесь две запятые
#    подряд, это синтаксическая ошибка. И разделитель по умолчанию у print —
#    пробел, а нам нужно, чтобы буквы склеивались через ***. За это отвечает
#    параметр sep (separator — разделитель).
# 3) print("***Version Python 3.10", ) — не хватало трёх звёздочек в конце,
#    их можно добавить прямо в строку либо через end='***'.
#
# sep  — что вставляется МЕЖДУ аргументами print
# end  — что печатается В КОНЦЕ всего вызова (по умолчанию перевод строки \n)

# Первая строка: просто печатаем готовую фразу целиком.
# Никаких sep/end тут не нужно — обычный вывод.
print("Привет!!!")

# Вторая строка: тоже выводим как есть, она в задании уже была правильная.
print("Я учусь программировать на Python!!!")

# Третья строка: буквы P Y T H O N передаём отдельными аргументами.
# sep='***' — между каждыми двумя соседними аргументами вставится "***".
# Получится: ***P***Y***T***H***O***N
# Первый аргумент — пустая строка '', она тоже участвует в выводе,
# поэтому перед первой P тоже окажется *** (print вставит sep между '' и 'P').
# end='\n' — это значение по умолчанию, можно не писать, оставил для наглядности.
print('', 'P', 'Y', 'T', 'H', 'O', 'N', sep='***', end='\n')

# Четвёртая строка: текст выводим как есть, а три звёздочки в конце
# делаем через end='***\n' — то есть вместо обычного перевода строки
# печатаем "***" и только потом переходим на новую строку.
print("***Version Python 3.10", end='***\n')
