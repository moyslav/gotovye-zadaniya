# Урок 10. Домашнее задание №1. Класс "Банковский счет".
#
# Требования:
# - приватные атрибуты __ballance и __pin (два подчёркивания = "приватно",
#   снаружи напрямую их не достать)
# - методы: set_ballance (пополнение по пину), get_ballance (снять по пину),
#   get_count (просто посмотреть баланс)
# - при снятии нельзя уйти в минус
#
# ПИН проверяем в каждом методе, где меняется или снимаются деньги.
# При трёх неверных попытках программа завершается.

class Account:
    """Банковский счёт с пин-кодом и балансом."""

    def __init__(self, ballance, pin):
        """Создаём счёт: запоминаем начальный баланс и пин.
        Оба атрибута приватные (два подчёркивания в начале имени)."""
        self.__ballance = ballance  # баланс (имя из условия задания)
        self.__pin = pin            # пин-код

    def set_ballance(self, money, pin):
        """Пополнение счёта. Работает только при верном пине."""
        if pin == self.__pin:
            # Пин верный — прибавляем деньги к балансу.
            self.__ballance += money
            print(f"Счёт пополнен на {money}. Текущий баланс: {self.__ballance}")
        else:
            print("Неверный пин")

    def get_ballance(self, money, pin):
        """Снятие денег. Пин должен совпасть, а денег на счету — хватить."""
        if pin != self.__pin:
            print("Неверный пин")
            return
        if money > self.__ballance:
            # Снимать больше, чем есть, нельзя — уйти в минус запрещено.
            print(f"Недостаточно средств. На счету только {self.__ballance}")
            return
        # Всё в порядке — уменьшаем баланс.
        self.__ballance -= money
        print(f"Снято {money}. Остаток: {self.__ballance}")

    def get_count(self):
        """Просто показывает баланс без пина (как в условии задания)."""
        print(f"Баланс счёта: {self.__ballance}")


# --- Основная часть: симуляция работы с банкоматом ---

# Создаём счёт: 1000 на балансе, пин 1111 (условия задания).
account = Account(1000, 1111)

# Счётчик неверных попыток пина.
tries = 0

# Крутим меню, пока пользователь не введёт "3".
while True:
    print("\n1 - пополнить счет, 2 - снять, 3 - выйти")
    choice = input("Ваш выбор: ")

    if choice == "1":
        # Пополнение: спрашиваем сумму и пин.
        money = float(input("Сумма пополнения: "))
        pin = int(input("Пин: "))
        if pin != 1111:
            # Считаем неправильные попытки.
            tries += 1
            if tries >= 3:
                print("Три неверных попытки. Программа завершена")
                break
        account.set_ballance(money, pin)

    elif choice == "2":
        # Снятие: тоже спрашиваем сумму и пин.
        money = float(input("Сумма снятия: "))
        pin = int(input("Пин: "))
        if pin != 1111:
            tries += 1
            if tries >= 3:
                print("Три неверных попытки. Программа завершена")
                break
        account.get_ballance(money, pin)

    elif choice == "3":
        # Пользователь решил выйти из программы.
        print("До свидания!")
        break

    else:
        # Неизвестный пункт меню.
        print("Нет такого пункта, попробуйте ещё раз")
