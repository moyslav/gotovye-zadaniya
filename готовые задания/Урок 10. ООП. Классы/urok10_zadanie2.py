# Урок 10. Домашнее задание №2. Класс Person с расчётом возраста.
#
# В конструкторе запоминаем ФИО, день/месяц/год рождения и год расчёта.
# Возраст считаем просто: год расчёта минус год рождения.
# (Точный возраст с учётом месяца и дня было бы правильнее,
# но по условию считаем по годам.)

class Person:
    """Человек: ФИО, дата рождения и расчёт возраста."""

    def __init__(self, name, day, month, year, current_year):
        """Сохраняем все данные о человеке в атрибутах объекта."""
        self.name = name              # ФИО
        self.day = day                # день рождения
        self.month = month            # месяц рождения
        self.year = year              # год рождения
        self.current_year = current_year  # год, на который считаем возраст

    def age(self):
        """Возвращает возраст: разница между текущим годом и годом рождения."""
        return self.current_year - self.year

    def print_person(self):
        """Печатает данные о человеке в формате из задания."""
        print(f"Имя: {self.name}, Дата рождения: {self.day}/{self.month}/{self.year}, Возраст: {self.age()}")


# --- Основная часть: проверяем класс на примере Elon Musk ---

# Создаём объект: Elon Musk, родился 28.06.1971, считаем на 2021 год
# (данные из примера в задании).
p = Person("Elon Mask", 28, 6, 1971, 2021)

# Печатаем информацию о человеке.
p.print_person()
