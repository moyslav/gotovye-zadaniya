# Урок 11. Домашнее задание №1. Класс "Прямоугольник" и его наследники.
#
# Три класса:
# - Rectangle — базовый: длина и ширина, методы периметра и площади
# - Parallelogram — наследник: те же стороны, но угол не 90 градусов,
#   поэтому площадь считается как a*b*sin(angle)
# - Square — наследник прямоугольника: все стороны равны
#
# Из math берём sin и радианы (sin в Python принимает угол в радианах,
# поэтому градусы надо перевести функцией radians).

import math


class Rectangle:
    """Прямоугольник со сторонами a и b."""

    def __init__(self, a, b):
        """Сохраняем длину и ширину в атрибутах."""
        self.a = a
        self.b = b

    def get_perimetr(self):
        """Периметр прямоугольника: 2 * (a + b)."""
        return 2 * (self.a + self.b)

    def get_square(self):
        """Площадь прямоугольника: a * b."""
        return self.a * self.b

    def print_info(self):
        """Выводит информацию о фигуре в формате из задания."""
        print(f"Периметр: {self.get_perimetr()}, Площадь: {self.get_square()}")


class Parallelogram(Rectangle):
    """Параллелограмм: стороны как у прямоугольника, но угол произвольный."""

    def __init__(self, a, b, angle):
        # Вызываем конструктор родителя, чтобы не дублировать код.
        super().__init__(a, b)
        self.angle = angle  # угол между сторонами в градусах

    def get_square(self):
        """Площадь параллелограмма: a * b * sin(угла).
        Угол переводим в радианы, потому что math.sin ждёт радианы."""
        return self.a * self.b * math.sin(math.radians(self.angle))


class Square(Rectangle):
    """Квадрат: прямоугольник с равными сторонами."""

    def __init__(self, a):
        # У квадрата обе стороны одинаковые, передаём a дважды.
        super().__init__(a, a)


# --- Основная часть: проверяем все три класса ---

# Прямоугольник 5 на 10 (пример из условия).
r = Rectangle(5, 10)
print("Прямоугольник 5x10:")
r.print_info()

# Параллелограмм со сторонами 5 и 10 и углом 30 градусов.
p = Parallelogram(5, 10, 30)
print("Параллелограмм 5x10 с углом 30°:")
p.print_info()

# Квадрат со стороной 5.
s = Square(5)
print("Квадрат 5x5:")
s.print_info()
