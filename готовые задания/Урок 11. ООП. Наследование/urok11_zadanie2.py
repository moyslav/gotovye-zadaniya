# Урок 11. Домашнее задание №2. Класс Money и наследники с ошибками.
#
# Класс Money хранит номинал и количество купюр.
# Наследники переопределяют метод count() и ВЫЗЫВАЮТ ОШИБКУ
# (raise), если купюр мало:
# - Money2000: нужно минимум 5 купюр
# - Money5000: нужно минимум 3 купюры
#
# raise = принудительно выбросить исключение. Его потом можно
# поймать через try/except или дать программе упасть с сообщением.

class Money:
    """Деньги: номинал купюры и их количество."""

    def __init__(self, demon, number):
        self.demon = demon    # номинал (например 100)
        self.number = number  # сколько купюр

    def count(self):
        """Считает общую сумму денег."""
        return self.demon * self.number


class Money2000(Money):
    """Купюры по 2000. Нужно минимум 5 штук."""

    def count(self):
        if self.number < 5:
            # Купюр слишком мало — вызываем ошибку.
            raise Exception("Купюр 2000 должно быть не меньше 5")
        # Иначе считаем как в родителе.
        return self.demon * self.number


class Money5000(Money):
    """Купюры по 5000. Нужно минимум 3 штуки."""

    def count(self):
        if self.number < 3:
            raise Exception("Купюр 5000 должно быть не меньше 3")
        return self.demon * self.number


# --- Основная часть ---

# Создаём объекты: обычные 100-е, 2000-е (4 штуки — мало!) и 5000-е.
m1 = Money(100, 10)    # 100 * 10 = 1000
m2 = Money2000(2000, 4)   # тут будет ошибка, купюр всего 4
m3 = Money5000(5000, 2)   # и тут, купюр всего 2

# Проверяем первый объект — он корректный.
print("Сумма m1:", m1.count())

# Второй и третий вызовут исключение. Ловим его через try/except,
# чтобы программа не падала, а печатала сообщение об ошибке.
try:
    print("Сумма m2:", m2.count())
except Exception as e:
    # e — само исключение, у него есть текст, который мы задали в raise.
    print("Ошибка:", e)

try:
    print("Сумма m3:", m3.count())
except Exception as e:
    print("Ошибка:", e)
