# Урок 12. Домашнее задание №1. Исключения ValueError и ZeroDivisionError.
#
# Нужно ловить две ошибки:
# 1) ValueError   — если пользователь ввёл не число ("abc" в int не превратишь)
# 2) ZeroDivisionError — если второе число ноль (на ноль делить нельзя)
#
# Программа не должна падать: ловим ошибки и печатаем сообщение,
# а затем просим числа заново, пока не получится корректный ввод.

# Цикл будет крутиться, пока пользователь не введёт корректные данные.
while True:
    try:
        # Спрашиваем оба числа ВНУТРИ try — любая ошибка ввода
        # попадёт в except ниже.
        a = float(input("Введите первое число: "))
        b = float(input("Введите второе число: "))
        # Пробуем разделить. Если b == 0, здесь вылетит ZeroDivisionError.
        result = a / b
    except ValueError:
        # Сюда попадаем, если int/float не смог преобразовать ввод.
        print("Ошибка: нужно вводить именно числа!")
        continue  # начинаем цикл заново
    except ZeroDivisionError:
        # А сюда — если второе число оказалось нулём.
        print("Ошибка: на ноль делить нельзя!")
        continue
    else:
        # Блок else выполняется, если ошибок НЕ было.
        # Выходим из цикла — данные корректные, ответ получен.
        print(f"Результат деления: {result}")
        break
