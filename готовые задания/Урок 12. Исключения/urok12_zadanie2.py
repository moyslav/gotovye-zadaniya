# Урок 12. Домашнее задание №2. Ошибка IndexError при выходе за границы списка.
#
# Список создаётся на 10 случайных чисел. Пользователь вводит индекс,
# программа показывает элемент. Если индекс вне диапазона 0..9,
# Python выбросит IndexError — её мы и ловим.
#
# ВАЖНО по условию: нельзя проверять len() или значение индекса
# перед обращением — должно быть НАСТОЯЩЕЕ исключение.

import random

# Создаём список на 10 случайных чисел.
numbers = [random.randint(0, 20) for _ in range(10)]
print("Список:", numbers)

# Просим индекс. Не проверяем его заранее — пусть будет ошибка,
# если индекс неправильный.
index = int(input("Введите индекс: "))

# Пытаемся достать элемент по индексу.
try:
    print(f"Элемент с индексом {index} равен {numbers[index]}")
except IndexError:
    # Индекс вышел за границы списка (или отрицательный слишком большой).
    print(f"Ошибка: индекса {index} не существует! Индексы от 0 до 9.")
