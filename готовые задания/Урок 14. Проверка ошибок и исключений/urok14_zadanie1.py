# Урок 14. Домашнее задание. Обработка ошибок пользовательского ввода.
#
# Вводят месяц (от 1 до 12), выводим время года. Если пользователь
# ввёл ерунду (не число), нужно поймать ValueError и не дать
# программе упасть.
#
# Логика:
# - числа 12, 1, 2  — зима
# - 3..5            — весна
# - 6..8            — лето
# - 9..11           — осень
# - числа вне 1..12 — сообщаем, что месяца не существует

# Цикл нужен, чтобы после ошибки снова спросить пользователя.
while True:
    try:
        # Пробуем превратить ввод в число. Если ввели "апрель" —
        # будет ValueError, который поймает except ниже.
        month = int(input("Введите месяц рождения (от 1 до 12): "))
    except ValueError:
        # Ввод — не число. Объясняем и просим заново.
        print("Это не число! Введите месяц цифрами от 1 до 12.")
        continue  # прыгаем на новую итерацию цикла

    # Ввод — число, дальше обычные проверки по диапазонам.
    if month == 12 or month == 1 or month == 2:
        print("Вы родились зимой")
        break  # всё получилось — выходим из цикла
    elif 3 <= month <= 5:
        print("Вы родились весной")
        break
    elif 6 <= month <= 8:
        print("Вы родились летом")
        break
    elif 9 <= month <= 11:
        print("Вы родились осенью")
        break
    else:
        # Число, но не месяц: 0, 13, 99 и т.п.
        print("Такого месяца не существует, попробуйте ещё раз")
        # break здесь не нужен — цикл сам продолжится.
