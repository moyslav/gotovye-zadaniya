# -*- coding: utf-8 -*-
# Урок 2. Задание №1.
# Программа спрашивает число и показывает его соседей: на 1 меньше и на 1 больше.
#
# Что тут важного:
# - input() всегда возвращает СТРОКУ, даже если пользователь ввёл цифры.
#   Поэтому перед вычислениями нужно превратить её в число через int().
# - f-строки удобны, чтобы не склеивать текст из кусочков через запятую.

# Просим число у пользователя. int() сразу превращает введённый текст в целое число.
# Если человек введёт "abc", программа упадёт с ошибкой — но обработку исключений
# мы проходим только в уроке 14, так что здесь это нормально.
x = int(input("Введите число: "))

# Считаем соседние числа. Это простая арифметика: вычесть или прибавить единицу.
menshe = x - 1   # число на единицу меньше введённого
bolshe = x + 1   # число на единицу больше введённого

# Выводим результат в требуемом формате через f-строку.
# В фигурных скобках Python подставляет значения переменных.
print(f"Введенное число: {x}, число меньше на 1: {menshe}, число большее на 1: {bolshe}")
