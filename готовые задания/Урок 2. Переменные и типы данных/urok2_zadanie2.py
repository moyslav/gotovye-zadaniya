# -*- coding: utf-8 -*-
# Урок 2. Задание №2.
# Программа знакомится с пользователем и показывает типы данных переменных.
#
# Идея задания — увидеть своими глазами, что в Python типы определяются
# автоматически (динамическая типизация): имя остаётся строкой (str),
# а год рождения и возраст мы сами делаем числами.

# Запрашиваем имя. Кавычки в input — это подсказка, которую видит пользователь.
# Так как имя — текст, ничего преобразовывать не нужно, это уже str.
my_name = input("Введите ваше имя: ")

# Год рождения пользователь вводит цифрами, но input отдаёт СТРОКУ.
# Если оставить как есть, то вычитание из неё потом не сработает.
# Поэтому оборачиваем в int() — получаем целое число.
year_of_birth = int(input("Введите год рождения: "))

# Считаем возраст: из текущего года вычитаем год рождения.
# Оба операнда — числа, значит и результат будет числом (int).
age = 2026 - year_of_birth

# По заданию нужно показать типы всех трёх переменных.
# Функция type() возвращает объект-тип, а print его красиво печатает,
# например: <class 'str'>, <class 'int'>.
print("Тип my_name:", type(my_name))
print("Тип year_of_birth:", type(year_of_birth))
print("Тип age:", type(age))

# Финальное сообщение по образцу из задания.
# Обратите внимание: f-строка сама превратит число age в текст, ничего конвертировать не надо.
print(f"Hello my name is: {my_name}, My age: {age}")
