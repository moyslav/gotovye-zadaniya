# Урок 2. Задание №3. Переводим минуты в формат ЧЧ:ММ.
#
# Логика простая:
# - в одном часе 60 минут, значит целых часов будет столько,
#   сколько раз 60 помещается в наше число (целочисленное деление //)
# - остаток от деления % — это и есть оставшиеся минуты
#
# Пример из задания: 136 минут = 2 часа (120 минут) + 16 минут остаток.

# Получаем количество минут от пользователя и сразу делаем из строки число.
minutes = int(input("Введите количество минут с начала дня: "))

# Целочисленное деление на 60 даёт количество полных часов.
# Например 136 // 60 = 2 (потому что 60*2=120, а 136-120=16).
hours = minutes // 60

# Остаток от деления — минуты, которые не дотягивают до полного часа.
# 136 % 60 = 16.
mins = minutes % 60

# Выводим по образцу. f-строка подставит посчитанные часы и минуты.
print(f"Прошло: {hours}:{mins} с начала дня")
