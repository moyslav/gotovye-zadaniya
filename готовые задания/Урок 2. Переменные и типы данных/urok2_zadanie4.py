# -*- coding: utf-8 -*-
# Урок 2. Задание №4. Закупка столов для кабинета.
#
# Условия:
# - за одним столом сидят ДВА сотрудника
# - у руководителя отдельный стол (1 стол)
# - ещё 1 стол на кофе-брейк
#
# Главная хитрость — округление вверх. Если сотрудников 5,
# то 5/2 = 2.5, а значит столов для них нужно ТРИ (два полных + один неполный).
# Для такого округления используем math.ceil — "потолок", т.е. всегда вверх.

# Подключаем стандартный модуль math, в нём живёт функция ceil.
import math

# Спрашиваем, сколько людей работает в кабинете.
workers = int(input("Введите количество работников в кабинете: "))

# Считаем, сколько столов нужно на сотрудников.
# math.ceil(workers / 2) округляет деление вверх до целого.
# Пример: 5 человек -> ceil(2.5) -> 3 стола.
tables_for_workers = math.ceil(workers / 2)

# Руководителю — отдельный стол, на кофе-брейк — ещё один.
# Их всегда ровно по одному, независимо от числа сотрудников.
tables_total = tables_for_workers + 1 + 1

# Показываем ответ. Можно было бы и в одну строку, но так нагляднее,
# видно из чего складывается итог.
print(f"Столов для сотрудников: {tables_for_workers}")
print(f"Всего столов нужно закупить: {tables_total}")
