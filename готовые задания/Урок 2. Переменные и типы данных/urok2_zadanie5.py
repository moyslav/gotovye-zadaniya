# -*- coding: utf-8 -*-
# Урок 2. Задание №5. Разбираемся с типами данных.
#
# Даны четыре переменные:
#   a = 22     — целое число            (int)
#   b = '43.0' — СТРОКА, хоть и похожа на число (str)
#   c = 30.99  — дробное число          (float)
#   n = 2 + 2j — комплексное число      (complex)
#
# Дальше проверяем, что получится при операциях над ними.
# Тут есть подвох: строку '43.0' нельзя прибавить к комплексному числу,
# Python выдаст TypeError. В задании есть подсказка "используйте функции
# преобразования типов" — значит строку сначала превращаем в float.

# Сначала просто создаём переменные из условия.
a = 22        # целое
b = '43.0'    # строка (не смотрите, что внутри цифры — для Python это текст)
c = 30.99     # дробное
n = 2 + 2j    # комплексное число, буква j обозначает мнимую часть

# Печатаем тип каждой переменной по образцу из задания.
# f-строка подставляет и значение, и то, что вернёт type().
print(f"Переменная a со значением {a} имеет тип: {type(a)}")
print(f"Переменная b со значением {b} имеет тип: {type(b)}")
print(f"Переменная c со значением {c} имеет тип: {type(c)}")
print(f"Переменная n со значением {n} имеет тип: {type(n)}")

print()  # пустая строка, чтобы вывод читался лучше

# --- Теперь проверяем результаты операций ---

# int + float = float. Python "повышает" тип до более общего.
# 22 + 30.99 = 52.99, это дробное число.
m = c + a
print(f"m = c + a = {m}, тип: {type(m)}")

# str + complex — так складывать нельзя, будет TypeError.
# Поэтому по подсказке задания сначала превращаем строку в число:
# float('43.0') даст 43.0, а уже его можно сложить с комплексным.
# float + complex = complex.
h = float(b) + n
print(f"h = float(b) + n = {h}, тип: {type(h)}")

# Обычное деление / в Python ВСЕГДА возвращает float,
# даже если числа делятся нацело: 22 / 2 = 11.0.
k = a / 2
print(f"k = a / 2 = {k}, тип: {type(k)}")
