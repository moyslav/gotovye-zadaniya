# -*- coding: utf-8 -*-
# Урок 3. Задание №1. Наибольшее и наименьшее из трёх чисел.
#
# Задание на ветвление, поэтому решаем честно через if/elif/else,
# а не готовыми функциями max()/min() (они тут, конечно, работают,
# но смысл урока — научиться сравнивать руками).

# Просим три числа. Каждое превращаем в float, чтобы работали и дробные.
a = float(input("Введите первое число: "))
b = float(input("Введите второе число: "))
c = float(input("Введите третье число: "))

# --- Ищем максимум ---
# Логика такая: сначала считаем, что максимум — это a.
# Потом по очереди проверяем, не оказались ли b или c больше.
if b > a:
    a = b  # нет, b больше — запоминаем его
if c > a:
    a = c  # и c ещё больше — запоминаем его
# После этих двух проверок в a лежит самое большое из трёх чисел.
maximum = a

# --- Ищем минимум ---
# Зеркальная логика: предполагаем, что минимум — это b,
# и если какое-то число оказалось меньше — перезаписываем.
if c < b:
    b = c
minimum = b

# Выводим результат.
print(f"Наибольшее число: {maximum}")
print(f"Наименьшее число: {minimum}")
