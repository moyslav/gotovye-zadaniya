# Урок 3. Задание №2. Определяем время года по месяцу рождения.
#
# Месяца по сезонам (по-нашему, по календарю):
#   зима  — 12, 1, 2
#   весна — 3, 4, 5
#   лето  — 6, 7, 8
#   осень — 9, 10, 11
#
# Используем if-elif-else, как требует задание.

# Просим номер месяца. Число от 1 до 12.
month = int(input("Введите месяц рождения (от 1 до 12): "))

# Проверяем диапазоны по очереди сверху вниз.
# Как только сработало одно условие — остальные пропускаются.
if month == 12 or month == 1 or month == 2:
    print("Вы родились зимой")
elif 3 <= month <= 5:
    # month >= 3 and month <= 5 — то же самое, но запись через цепочку короче
    print("Вы родились весной")
elif 6 <= month <= 8:
    print("Вы родились летом")
elif 9 <= month <= 11:
    print("Вы родились осенью")
else:
    # Сюда попадаем, если номер вообще не из диапазона 1-12,
    # например 0 или 25. Хорошая привычка — обрабатывать такое.
    print("Такого месяца не существует")
