# Урок 3. Задание №3. Вывод всех чисел от 0 до N через while.
#
# Цикл while работает, пока условие истинно. Важно не забыть
# увеличивать счётчик внутри цикла, иначе получится бесконечный цикл.

# Введённое число должно быть целым и положительным.
n = int(input("Введите целое положительное число: "))

# Счётчик начинаем с нуля — с него и начинается вывод.
i = 0

# Крутим цикл, пока счётчик не дошёл до введённого числа включительно.
while i <= n:
    print(i)  # печатаем текущее значение
    i += 1    # ОБЯЗАТЕЛЬНО увеличиваем счётчик, иначе цикл вечный
