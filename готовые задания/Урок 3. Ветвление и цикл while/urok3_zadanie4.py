# Урок 3. Задание №4. Считаем чётные цифры числа и их сумму через while.
#
# Идея разбора числа: берём последнюю цифру как остаток от деления на 10
# (num % 10), проверяем её на чётность, потом "отрезаем" её целочисленным
# делением на 10 (num //= 10). И так, пока число не кончится.

# Число вводит пользователь.
num = int(input("Введите целое число: "))

k = 0  # счётчик чётных цифр
s = 0  # сумма чётных цифр

# Работаем, пока в числе остались цифры.
while num > 0:
    digit = num % 10   # последняя цифра числа
    if digit % 2 == 0:  # проверяем чётность: остаток от деления на 2 равен нулю
        k += 1          # ещё одна чётная цифра
        s += digit      # прибавляем её к сумме
    num //= 10  # отрезаем последнюю цифру (например 123 -> 12)

# Показываем результат. В f-строке \n — перенос строки,
# чтобы сумма была на отдельной строке.
print(f"Количество четных цифр {k} \nСумма четных цифр {s}")
