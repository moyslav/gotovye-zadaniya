# Урок 3. Задание №5. Числа из промежутка от X до R через while.
#
# По условию X < R, и ОБА края промежутка включаются в вывод и подсчёт.

# Запрашиваем числа. Пользователь обязан ввести X меньше R,
# поэтому на всякий случай проверим это и переспросим, если перепутал.
x = int(input("Введите число X: "))
r = int(input("Введите число R (больше X): "))

# Простая защита от дурака: если X >= R, просим ввести заново.
while x >= r:
    print("Ошибка: X должно быть меньше R!")
    x = int(input("Введите число X: "))
    r = int(input("Введите число R (больше X): "))

count = 0  # здесь посчитаем, сколько чисел в промежутке

# Идём от X до R включительно, поэтому условие i <= r.
i = x
while i <= r:
    print(i)     # печатаем текущее число промежутка
    count += 1   # и считаем его
    i += 1       # переходим к следующему

# В конце выводим количество. Обратите внимание на формат из задания.
print(f"В промежутке от X до R {count} чисел")
