# Урок 3. Задание №6. Факториал числа через while.
#
# Факториал — это произведение всех чисел от 1 до F.
# Например: 3! = 1 * 2 * 3 = 6, а 7! = 5040.
#
# Приём: заводим переменную-накопитель и умножаем её на каждое
# следующее число. Начинать надо с ЕДИНИЦЫ, а не с нуля —
# иначе всё произведение всегда будет нулём.

f = int(input("Введите число F: "))

result = 1  # накопитель произведения (1 — нейтральный элемент для умножения)
i = 1       # счётчик от 1 до F

while i <= f:
    result = result * i  # домножаем накопитель на текущее число
    i += 1               # двигаемся к следующему множителю

# Выводим готовый факториал.
print(f"Факториал числа {f} равен {result}")
