# Урок 4. Задание №1. Нечётные числа от 3 до 150 циклом for.
#
# Подвох задания: нельзя использовать if для проверки нечётности.
# Но и не нужно — range умеет делать шаг! Третий аргумент range —
# это шаг. Начинаем с 3 и каждый раз прибавляем 2:
# 3, 5, 7, 9 ... — все числа нечётные сами собой.
#
# В range правая граница НЕ включается, поэтому пишем 151,
# чтобы последнее число было 150... стоп, 150 чётное, последнее
# нечётное — 149, и range(3, 151, 2) как раз закончится на 149.

# Перебираем нечётные числа от 3 до 149.
for i in range(3, 151, 2):
    print(i)
