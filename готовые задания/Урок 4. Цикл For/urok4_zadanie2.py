# Урок 4. Задание №2. Сумма чётных чисел от 0 до N.
#
# Хитрость та же, что и с нечётными: не нужен if.
# Чётные числа начинаются с 0 и идут с шагом 2:
# range(0, N + 1, 2) даст 0, 2, 4, 6 ...
# Единица прибавляется к границе, потому что range правую границу
# не включает, а N по условию должно войти (если оно чётное).

# N вводит пользователь, сразу превращаем в целое число.
n = int(input("Введите число N: "))

total = 0  # накопитель суммы

# Шагаем по чётным числам с шагом 2.
for i in range(0, n + 1, 2):
    total += i  # прибавляем текущее чётное число к сумме

# Печатаем итог.
print(f"Сумма чётных чисел от 0 до {n} равна {total}")
