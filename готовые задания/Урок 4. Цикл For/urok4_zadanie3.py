# Урок 4. Задание №3. Числа от 1 до T с пропусками через continue.
#
# Числа 7, 13, 21 и 29 нужно пропустить. Оператор continue
# перепрыгивает к следующему витку цикла, не выполняя код ниже.
# Как раз то, что нам нужно.

# T должно быть не меньше 35, иначе смысла в задании нет.
t = int(input("Введите число T (не меньше 35): "))

# Идём от 1 до T включительно, поэтому t + 1 в range.
for i in range(1, t + 1):
    # Если число попало в чёрный список — пропускаем его.
    if i == 7 or i == 13 or i == 21 or i == 29:
        continue  # прыгаем к следующей итерации, print ниже не выполнится
    print(i)
