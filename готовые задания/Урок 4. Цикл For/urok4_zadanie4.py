# Урок 4. Задание №4. Угадай число.
#
# Программа загадывает случайное число от 0 до 4,
# пользователь вводит варианты, пока не угадает.
# Выход из цикла — оператор break.

# Подключаем модуль для генерации случайных чисел.
import random

# random.randint(a, b) возвращает случайное ЦЕЛОЕ число,
# причём ОБА края диапазона включаются (в отличие от range!).
secret = random.randint(0, 4)

# Сообщим пользователю диапазон, чтобы он понимал, что вводить.
print("Я загадал число от 0 до 4. Попробуй угадать!")

# Бесконечный цикл: выходим из него только через break при угадывании.
while True:
    # Просим вариант. Предположим, что пользователь введёт число,
    # и превратим строку в int.
    guess = int(input("Твой вариант: "))

    if guess == secret:
        # Угадал — выходим из цикла командой break.
        print("Угадал! Это было число", secret)
        break
    else:
        # Не угадал — печатаем подсказку и цикл продолжается.
        print("Мимо, пробуй ещё")
