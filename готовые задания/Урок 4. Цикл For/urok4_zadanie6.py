# Урок 4. Задание №6. Квадраты чётных и кубы нечётных чисел.
#
# Для каждого числа от 1 до N:
#   чётное -> выводим его квадрат (степень 2)
#   нечётное -> выводим его куб (степень 3)
# Степени считаем оператором ** (например, i ** 3 — это i в кубе).

# N вводит пользователь.
n = int(input("Введите число N: "))

# Перебираем все числа от 1 до N включительно.
for i in range(1, n + 1):
    if i % 2 == 0:
        # Чётное число — возводим в квадрат и печатаем с пояснением.
        print(f"{i} в степени 2 = {i ** 2}")
    else:
        # Нечётное — в куб.
        print(f"{i} в степени 3 = {i ** 3}")
