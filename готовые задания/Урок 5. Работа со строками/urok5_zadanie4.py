# -*- coding: utf-8 -*-
# Урок 5. Задание №4. Считаем слова в строке.
#
# По условию слова разделены пробелами, а первый и последний
# символ строки — не пробел. Значит достаточно разбить строку
# методом split() и посчитать длину получившегося списка.
# split() без аргументов сам справится с двойными пробелами —
# пустых слов в списке не будет.

# Получаем строку от пользователя.
s = input("Введите строку: ")

# Режем по пробелам: 'мама мыла раму' -> ['мама', 'мыла', 'раму'].
words = s.split()

# Длина списка = количество слов. Выводим её.
print(f"В строке {len(words)} слов")
