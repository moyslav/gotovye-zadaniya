# Урок 5. Задание №5. Сменить регистр букв и убрать пробелы.
#
# Тут всё делается двумя методами строк:
# - swapcase() меняет регистр каждой буквы на противоположный:
#   большие становятся маленькими и наоборот
# - replace(' ', '') заменяет пробел на пустоту, т.е. просто удаляет его
#
# Важный момент: методы строк НЕ меняют саму строку,
# они возвращают новую. Поэтому результат надо сохранять в переменную.

# Вводим строку.
s = input("Введите строку: ")

# Сначала меняем регистр. 'ПриВеТ' -> 'пРИвЕт'.
s = s.swapcase()

# Потом удаляем все пробелы: заменяем ' ' на '' (пустую строку).
s = s.replace(' ', '')

# Печатаем то, что получилось.
print(s)
