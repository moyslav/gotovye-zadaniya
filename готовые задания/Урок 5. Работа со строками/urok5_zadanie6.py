# Урок 5. Задание №6. Десять случайных дробных чисел с двумя знаками.
#
# Генерируем 10 вещественных чисел от 0 до 10 через random.uniform(),
# а при выводе округляем до 2 знаков прямо внутри f-строки:
# формат {x:.2f} означает "число с плавающей точкой, 2 знака после точки".

# Подключаем модуль случайных чисел.
import random

# Цикл на 10 повторений: i будет от 1 до 10.
for i in range(1, 11):
    # uniform(a, b) даёт случайное дробное число в диапазоне от a до b.
    num = random.uniform(0, 10)
    # Выводим по образцу, ограничивая знаки после точки форматом :.2f.
    print(f"{i} число = {num:.2f}")
