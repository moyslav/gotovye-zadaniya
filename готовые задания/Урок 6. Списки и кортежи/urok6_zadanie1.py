# -*- coding: utf-8 -*-
# Урок 6. Задание №1. Удалить буквы 'a', 'e', 'u' из строки-списка.
#
# По заданию нужно превратить строку в СПИСОК (то есть в список символов),
# удалить из него ненужные буквы и вывести результат.
#
# Способ удаления: перебираем список и собираем новый только
# из нужных символов. Можно было бы и через remove(), но remove()
# удаляет только первое вхождение, пришлось бы гонять в цикле —
# так проще и надёжнее.

# Вводим строку на английском.
s = input("Введите строку на английском: ")

# Превращаем строку в список символов: 'hello' -> ['h','e','l','l','o'].
letters = list(s)

# Создаём пустой список для результата.
result = []

# Перебираем символы и оставляем только те, что не под удаление.
for char in letters:
    if char not in ('a', 'e', 'u'):
        # Символ не из чёрного списка — берём его.
        result.append(char)

# Печатаем и список, и собранную из него строку.
# join склеивает символы обратно в строку.
print("Список после удаления:", result)
print("Строка после удаления:", ''.join(result))
