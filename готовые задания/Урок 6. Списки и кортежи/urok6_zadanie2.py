# Урок 6. Задание №2. Список из N случайных чисел от 0 до 20.
#
# Заполняем список в цикле: N раз добавляем случайное число.
# randint(0, 20) включает и 0, и 20.

import random  # модуль для случайных чисел

# Спрашиваем размер будущего списка.
n = int(input("Введите количество элементов N: "))

numbers = []  # пока список пустой

# Повторяем N раз.
for i in range(n):
    # Генерируем случайное целое и сразу добавляем в конец списка.
    numbers.append(random.randint(0, 20))

# Показываем готовый список.
print("Получился список:", numbers)
