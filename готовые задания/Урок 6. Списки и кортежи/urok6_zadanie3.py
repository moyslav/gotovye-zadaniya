# Урок 6. Задание №3. Удалить элементы с чётными индексами.
#
# ВАЖНЫЙ ПОДВОХ: нельзя удалять элементы из списка прямо во время
# перебора циклом for — индексы сдвигаются, и часть элементов
# перепрыгивается. Поэтому собираем новый список из элементов
# с НЕчётными индексами (1, 3, 5 ...).
#
# Чётный индекс — 0, 2, 4 ... (помним, что нумерация с нуля!).

numbers = []  # сюда соберём введённые числа

# По заданию нужно 10 чисел с клавиатуры.
for i in range(10):
    num = int(input(f"Введите {i + 1}-е число: "))
    numbers.append(num)

print("Исходный список:", numbers)

# Перебираем индексы от 0 до 9.
result = []
for i in range(len(numbers)):
    if i % 2 != 0:
        # Индекс нечётный — этот элемент выживает.
        result.append(numbers[i])

# Выводим то, что осталось.
print("После удаления чётных индексов:", result)
