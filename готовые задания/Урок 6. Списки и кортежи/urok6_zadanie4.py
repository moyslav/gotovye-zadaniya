# Урок 6. Задание №4. Сортировка списка и сумма двух элементов.
#
# План: создать список на 10 случайных чисел от 0 до 100,
# отсортировать по возрастанию методом sort(), а потом сложить
# ВТОРОЙ и ПРЕДПОСЛЕДНИЙ элементы.
#
# С индексами: второй элемент — это numbers[1] (нумерация с нуля!),
# предпоследний — numbers[-2] (отрицательный индекс считает с конца).

import random

# Создаём список из 10 случайных чисел через генератор списков.
# Запись [random.randint(0, 100) for _ in range(10)] читается так:
# "10 раз сгенерируй случайное число и собери их в список".
# Подчёркивание _ — переменная-заглушка, значение которой нам не нужно.
numbers = [random.randint(0, 100) for _ in range(10)]

print("До сортировки:   ", numbers)

# sort() сортирует список НА МЕСТЕ, ничего не возвращает.
numbers.sort()

print("После сортировки:", numbers)

# Складываем второй (индекс 1) и предпоследний (индекс -2) элементы.
total = numbers[1] + numbers[-2]
print(f"Сумма второго ({numbers[1]}) и предпоследнего ({numbers[-2]}) элементов: {total}")
