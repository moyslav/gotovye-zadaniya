# Урок 6. Задание №5. Удалить элементы меньше 5 и найти среднее.
#
# План:
# 1. список на 10 случайных чисел (возьму диапазон от 0 до 20 —
#    конец диапазона больше 5, как и требуется)
# 2. убрать все элементы меньше 5
# 3. посчитать среднее арифметическое: сумма / количество

import random

# Заполняем список случайными числами от 0 до 20.
numbers = [random.randint(0, 20) for _ in range(10)]
print("Исходный список:", numbers)

# Собираем новый список только из чисел, которые НЕ меньше 5.
# Так же, как и с удалением по индексам — не трогаем исходный список
# во время перебора, а собираем новый.
filtered = []
for num in numbers:
    if num >= 5:
        filtered.append(num)

print("После удаления чисел меньше 5:", filtered)

# Среднее арифметическое = сумма всех элементов / количество элементов.
# Функции sum() и len() делают это без ручных циклов.
average = sum(filtered) / len(filtered)

# Выводим среднее, округлив до 2 знаков для красоты.
print(f"Среднее арифметическое: {average:.2f}")
