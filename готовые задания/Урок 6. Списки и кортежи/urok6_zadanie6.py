# Урок 6. Задание №6. Произведение элементов, кратных 3, с чётным индексом.
#
# Тут ДВА условия одновременно:
#   1) сам элемент делится на 3 без остатка (num % 3 == 0)
#   2) его ИНДЕКС чётный (индексы 0, 2, 4 ...)
#
# Важно не путать: чётность проверяем у ИНДЕКСА, кратность — у ЗНАЧЕНИЯ.

import random

# Список на 20 случайных чисел от 0 до 20.
numbers = [random.randint(0, 20) for _ in range(20)]
print("Список:", numbers)

# Накопитель произведения. Начинаем с 1 (не с 0, иначе всё обнулится!).
product = 1

# Перебираем индексы — нам нужны и индекс, и значение одновременно.
for i in range(len(numbers)):
    # Проверяем оба условия сразу через and.
    if numbers[i] % 3 == 0 and i % 2 == 0:
        product *= numbers[i]  # домножаем накопитель

# Если ни одного подходящего числа не нашлось, произведение останется 1.
# Выведем его как есть — формально это правильный ответ для пустого набора.
print(f"Произведение элементов, кратных 3, с чётным индексом: {product}")
