# Урок 6. Задание №7. Кортеж из 15 квадратов чисел.
#
# Кортеж (tuple) — как список, но его нельзя менять после создания.
# Задание требует заполнить кортеж через ГЕНЕРАТОР: собираем список
# квадратов и превращаем его в кортеж функцией tuple().

# Генератор списков: для каждого n от 1 до 15 кладём n в квадрате.
# range(1, 16) — правая граница не включается, поэтому 16, чтобы дойти до 15.
squares = tuple(n ** 2 for n in range(1, 16))

# Выводим кортеж целиком.
print(squares)
