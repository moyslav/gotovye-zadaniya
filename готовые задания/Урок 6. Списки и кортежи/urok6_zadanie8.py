# Урок 6. Задание №8. Счастливый билет.
#
# Билет счастливый, если сумма ПЕРВЫХ трёх цифр равна сумме
# ПОСЛЕДНИХ трёх. Номер — 6 цифр, от 000000 до 999999.
#
# Важный момент: номер храним как СТРОКУ из 6 символов, потому что
# нам важны именно цифры, а не значение числа. Билет 012345 —
# это шесть цифр, и ноль в начале терять нельзя.
#
# Разбор: первые три цифры — s[0], s[1], s[2],
# последние три — s[3], s[4], s[5].

# Просим номер билета. Не превращаем в число — работаем со строкой!
ticket = input("Введите номер билета (6 цифр): ")

# Проверяем, что номер вообще корректный: 6 символов и все цифры.
if len(ticket) != 6 or not ticket.isdigit():
    print("Номер должен состоять из 6 цифр!")
else:
    # Считаем сумму первых трёх цифр.
    # int() нужен, потому что символы '1' и числа 1 — разные вещи.
    first = int(ticket[0]) + int(ticket[1]) + int(ticket[2])
    # Считаем сумму последних трёх цифр.
    last = int(ticket[3]) + int(ticket[4]) + int(ticket[5])

    # Сравниваем и выводим вердикт.
    if first == last:
        print("Билет счастливый!")
    else:
        print("Билет обычный. Повезёт в следующий раз")
