# -*- coding: utf-8 -*-
# Урок 7. Задание №1. Русско-английский словарь.
#
# Словарь (dict) хранит пары "ключ: значение". Ключ здесь — русское
# слово, значение — перевод. Ищем перевод обычным обращением по ключу.
#
# Нюанс: если ключа в словаре нет, обычное обращение словарь[ключ]
# вызовет ошибку KeyError. Поэтому сначала проверяем ключ через in.

# Создаём словарь с 10 словами (2 из условия + 8 своих).
slovar = {
    "кот": "cat",
    "мышь": "mouse",
    "собака": "dog",
    "животные": "animals",
    "дом": "house",
    "книга": "book",
    "город": "city",
    "дерево": "tree",
    "вода": "water",
    "друг": "friend",
}

# Пользователь вводит слово, которое хочет перевести.
word = input("Введите русское слово: ")

# Проверяем, есть ли такое слово в словаре.
if word in slovar:
    # Слово найдено — достаём перевод по ключу и выводим.
    print(f"Слово {word} переводится как: {slovar[word]}.")
else:
    # Ключа нет — честно об этом говорим.
    print(f"Слова {word} нет в словаре")
