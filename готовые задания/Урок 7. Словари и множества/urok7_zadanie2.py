# Урок 7. Задание №2. Словарь + возможность добавлять свои слова.
#
# Берём словарь из первого задания и даём пользователю добавить
# 5 новых слов: сначала русское слово, потом перевод.
# Добавление в словарь — просто присваивание: словарь[ключ] = значение.

# Исходный словарь из задания №1.
slovar = {
    "кот": "cat",
    "мышь": "mouse",
    "собака": "dog",
    "животные": "animals",
    "дом": "house",
    "книга": "book",
    "город": "city",
    "дерево": "tree",
    "вода": "water",
    "друг": "friend",
}

# Цикл на 5 добавлений.
for i in range(5):
    # Запрашиваем пару: слово и его перевод.
    ru = input(f"Введите русское слово {i + 1} из 5: ")
    en = input("Введите перевод: ")
    # Добавляем пару в словарь.
    slovar[ru] = en
    # Небольшая обратная связь, чтобы пользователь видел результат.
    print(f'В словарь добавлено: "{ru}" : "{en}"')

# Теперь словарь пополнился — можно переводить как обычно.
word = input("Введите русское слово для перевода: ")

if word in slovar:
    print(f"Слово {word} переводится как: {slovar[word]}.")
else:
    print(f"Слова {word} нет в словаре")
