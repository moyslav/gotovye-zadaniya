# -*- coding: utf-8 -*-
# Урок 7. Задание №3. Словарь "номер билета: студент".
#
# Ключ — случайный трёхзначный номер (0..999), значение — имя и фамилия.
# Главное условие: номер не должен повторяться, поэтому перед добавлением
# проверяем, нет ли уже такого ключа в словаре.

import random

slovar = {}  # пустой словарь для студентов

# Заполняем ровно 10 записями.
for i in range(10):
    # Сначала спрашиваем ФИО.
    name = input(f"Введите имя и фамилию {i + 1} из 10: ")

    # Генерируем номер, пока не найдём свободный.
    while True:
        n = random.randint(0, 999)  # случайный трёхзначный номер
        if n not in slovar:
            # Такой номер ещё не использовался — берём его.
            break
        # Если номер занят, цикл повторится и сгенерирует новый.

    # Записываем студента в словарь под свободным номером.
    slovar[n] = name

# Показываем весь словарь.
print(slovar)
