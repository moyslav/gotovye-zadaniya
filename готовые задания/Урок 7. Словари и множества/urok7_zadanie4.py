# Урок 7. Задание №4. Фильтруем ключи и значения словаря по длине.
#
# Задание на методы keys() и values():
# - вывести ключи длиной 4 символа и меньше
# - вывести значения, у которых ключи длиной 5 символов и больше
#
# keys() отдаёт все ключи, values() — все значения.
# Но чтобы сопоставить ключ с его значением, удобнее идти по items() —
# он отдаёт пары "ключ, значение" сразу.

# Словарь из первого задания.
slovar = {
    "кот": "cat",
    "мышь": "mouse",
    "собака": "dog",
    "животные": "animals",
    "дом": "house",
    "книга": "book",
    "город": "city",
    "дерево": "tree",
    "вода": "water",
    "друг": "friend",
}

# --- Часть 1: ключи длиной <= 4 ---
# Идём по keys() и проверяем длину каждого ключа функцией len().
print("Ключи, длина которых меньше или равна 4 символам:")
for key in slovar.keys():
    if len(key) <= 4:
        print(key)

# --- Часть 2: значения ключей длиной >= 5 ---
# Тут нужен и ключ, и значение одновременно, поэтому items().
print("Значения ключей, длина которых больше или равна 5 символам:")
for key, value in slovar.items():
    if len(key) >= 5:
        print(value)
