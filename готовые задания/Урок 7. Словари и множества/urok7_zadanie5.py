# Урок 7. Задание №5. Операции над множествами.
#
# Нужно два множества по 20 элементов (случайные числа 0..100),
# причём числа НЕ должны повторяться внутри множества —
# множество само по себе хранит только уникальные значения,
# но по условию перед добавлением надо проверять наличие.
#
# Дальше выводим три операции:
# - объединение  (union)          — всё, что есть хотя бы в одном
# - разность     (difference)     — то, что есть в первом и нет во втором
# - пересечение  (intersection)   — то, что есть в обоих сразу

import random

# Функция для заполнения множества без повторов.
def fill_set():
    s = set()          # создаём пустое множество
    while len(s) < 20: # крутим, пока не наберём 20 уникальных чисел
        n = random.randint(0, 100)
        if n not in s: # проверка, как требует задание
            s.add(n)   # добавляем, только если такого ещё нет
    return s

# Заполняем оба множества.
set1 = fill_set()
set2 = fill_set()

print("Первое множество: ", set1)
print("Второе множество:", set2)
print()

# Объединение: | — всё из обоих множеств без дублей.
print("Объединение:", set1 | set2)

# Разность: - — элементы первого множества, которых нет во втором.
print("Разность (первое минус второе):", set1 - set2)

# Пересечение: & — только общие элементы.
print("Пересечение:", set1 & set2)
