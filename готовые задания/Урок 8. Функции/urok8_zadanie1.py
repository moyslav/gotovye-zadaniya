# Урок 8. Задание №1. Функция площади круга.
#
# Формула: S = pi * R^2. Радиус запрашиваем у пользователя,
# считаем внутри функции и ВОЗВРАЩАЕМ результат (return),
# а print уже делаем снаружи — так функция остаётся универсальной:
# её можно использовать не только для вывода, но и в расчётах.

# Константа из условия задания (вместо math.pi берем 3.14, как сказано).
pi = 3.14

def s_circle(r):
    """Считает площадь круга по радиусу r. Возвращает площадь."""
    # Возводим радиус в квадрат оператором ** и умножаем на pi.
    return pi * r ** 2

# --- Основная часть программы ---

# Радиус вводит пользователь, сразу превращаем в число.
# Берем float, чтобы можно было ввести, например, 2.5.
radius = float(input("Введите радиус круга: "))

# Вызываем функцию и сохраняем результат в переменную.
square = s_circle(radius)

# Печатаем ответ.
print(f"Площадь круга с радиусом {radius} равна {square}")
