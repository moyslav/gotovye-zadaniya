# Урок 8. Задание №2. Функция: количество чётных цифр и их сумма.
#
# Это то же задание, что было в уроке 3, но теперь логика завернута
# в функцию. Функция возвращает ДВА значения через запятую —
# на самом деле это кортеж из двух элементов, и его можно
# распаковать в две переменные при вызове.

def even_digits(num):
    """Считает чётные цифры числа num.
    Возвращает кортеж (количество, сумма)."""
    k = 0  # счётчик чётных цифр
    s = 0  # сумма чётных цифр
    # Разбираем число по цифрам: берём последнюю цифру и отрезаем её.
    while num > 0:
        digit = num % 10    # последняя цифра
        if digit % 2 == 0:  # цифра чётная?
            k += 1
            s += digit
        num //= 10          # убираем последнюю цифру
    return k, s  # возвращаем сразу два значения

# --- Основная часть ---

# Запрашиваем число у пользователя.
number = int(input("Введите число: "))

# Вызываем функцию и распаковываем результат в две переменные.
count, total = even_digits(number)

# Выводим результат в формате из задания.
print(f"Количество четных цифр {count} \nСумма четных цифр {total}")
