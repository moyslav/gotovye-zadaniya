# Урок 8. Задание №3. Факториал через функцию (без модуля math).
#
# Факториал числа F — произведение всех чисел от 1 до F.
# Например: 5! = 1*2*3*4*5 = 120.
#
# Внутри функции обычный цикл с накопителем.
# Важно: 0! = 1 по определению — цикл от 1 до 0 не выполнится ни разу,
# и накопитель останется 1, так что этот случай обработается сам собой.

def factorial(f):
    """Считает факториал числа f и возвращает его."""
    result = 1  # накопитель, начинаем с 1 (нейтральный элемент умножения)
    # Перебираем множители от 1 до f включительно.
    for i in range(1, f + 1):
        result *= i  # домножаем накопитель
    return result

# --- Основная часть ---

# Число вводит пользователь.
n = int(input("Введите число: "))

# Вызываем функцию и печатаем результат.
print(f"Факториал числа {n} равен {factorial(n)}")
