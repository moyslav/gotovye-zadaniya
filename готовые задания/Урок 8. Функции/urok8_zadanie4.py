# Урок 8. Задание №4. Функция: чётные числа списка по убыванию.
#
# На вход — список на 15 случайных чисел от 1 до 30.
# Функция должна вернуть отсортированный (по убыванию) список
# только из чётных значений.
#
# ВАЖНО из условия: заполнить список сразу чётными числами нельзя —
# вся обработка происходит внутри функции.

import random

def even_sorted(lst):
    """Из списка lst берет только чётные числа и сортирует их по убыванию."""
    # Сначала отбираем чётные числа в новый список.
    evens = []
    for num in lst:
        if num % 2 == 0:  # остаток от деления на 2 — проверка чётности
            evens.append(num)
    # Сортируем по убыванию: параметр reverse=True разворачивает порядок.
    evens.sort(reverse=True)
    return evens

# --- Основная часть ---

# Создаем исходный список из 15 случайных чисел от 1 до 30.
# Числа могут быть и чётными, и нечётными — фильтрует их уже функция.
numbers = [random.randint(1, 30) for _ in range(15)]
print("Исходный список:", numbers)

# Передаём список в функцию и печатаем то, что она вернула.
print("Чётные по убыванию: ", even_sorted(numbers))
