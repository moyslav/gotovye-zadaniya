# Урок 8. Задание №5. Функция: только уникальные элементы списка.
#
# Список на 20 случайных чисел от 1 до 10 — повторы в нём точно будут.
# Функция должна вернуть список, где каждый элемент встречается один раз.
#
# Подвох: нельзя просто превратить список в set() и обратно,
# хотя это работает. Лучше пройти по списку и собирать новый список,
# проверяя, не добавляли ли мы такое число уже — так порядок
# элементов сохраняется.

import random

def unique(lst):
    """Возвращает список без повторов (порядок сохраняется)."""
    result = []  # сюда кладём только то, чего ещё не было
    for num in lst:
        if num not in result:  # проверяем, есть ли уже такое число
            result.append(num)
    return result

# --- Основная часть ---

# Список на 20 чисел от 1 до 10 — повторов не избежать.
numbers = [random.randint(1, 10) for _ in range(20)]
print("Исходный список: ", numbers)

# Убираем повторы через нашу функцию.
print("Уникальные элементы:", unique(numbers))
