# Урок 8. Задание №6. Функция проверки числа на простоту.
#
# Простое число делится только на 1 и на само себя.
# Примеры: 2, 3, 5, 7, 11, 13 ...
# Единица НЕ простое число (так договорились математики).
#
# Алгоритм: пробуем делить число на все делители от 2 до n-1.
# Если хоть где-то делится без остатка — число не простое.
# Оптимизировать не будем, урок ведь про функции, а не про математику.

def is_prime(n):
    """Проверяет, является ли число n простым. Возвращает True/False."""
    if n < 2:
        # 0 и 1 простыми не считаются.
        return False
    # Перебираем возможные делители от 2 до n-1.
    for i in range(2, n):
        if n % i == 0:
            # Нашся делитель — число составное, дальше можно не проверять.
            return False
    # Ни один делитель не подошёл — число простое.
    return True

# --- Основная часть ---

# Число вводит пользователь.
num = int(input("Введите число: "))

# Вызываем функцию и выводим результат в зависимости от ответа.
if is_prime(num):
    print(f"Число {num} является простым")
else:
    print(f"Число {num} не является простым")
