# Урок 9. Задание №2. Числа Фибоначчи через рекурсию.
#
# Числа Фибоначчи: каждое следующее число — сумма двух предыдущих.
# Последовательность начинается с 0: 0, 1, 1, 2, 3, 5, 8, 13 ...
#
# Функция принимает количество элементов и печатает их по одному.
# Рекурсивный вариант: fib(k) возвращает k-е число Фибоначчи,
# а печать всей последовательности делает обычный цикл.
# Это нагляднее и быстрее, чем печатать рекурсией напрямую.

def fib(n):
    """Возвращает n-е число Фибоначчи (нумерация с нуля)."""
    # Базовые случаи рекурсии: fib(0) = 0, fib(1) = 1.
    if n == 0:
        return 0
    if n == 1:
        return 1
    # Рекурсивный шаг: сумма двух предыдущих чисел.
    return fib(n - 1) + fib(n - 2)

# --- Основная часть ---

# Сколько элементов последовательности нужно вывести.
count = int(input("Введите количество элементов: "))

# Печатаем числа по порядку: от 0-го до count-1-го.
for i in range(count):
    print(fib(i))
