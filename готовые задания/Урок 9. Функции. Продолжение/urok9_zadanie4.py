# Урок 9. Задание №4. map() и lambda: чётные умножить на 2, нечётные на 3.
#
# map(функция, последовательность) применяет функцию к КАЖДОМУ
# элементу и возвращает новую последовательность.
# Внутри лямбды проверяем чётность через тернарный оператор:
#   (значение_если_да) if (условие) else (значение_если_нет)

import random

# Исходный список: 10 случайных чисел от 1 до 20.
numbers = [random.randint(1, 20) for _ in range(10)]
print("Первый список:      ", numbers)

# Применяем лямбду к каждому элементу.
# Логика: если x чётное (x % 2 == 0) — умножаем на 2, иначе на 3.
new_numbers = list(map(lambda x: x * 2 if x % 2 == 0 else x * 3, numbers))

# Выводим результат.
print("Получившийся список:", new_numbers)
